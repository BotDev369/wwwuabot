/**
 * Типи композера — модалки швидкого створення, яку відкриває той, кому це
 * створення належить: «+» у футері панелі, «+» на екрані нотаток, дошка
 * оголошень.
 *
 * Композер спільний для обох оболонок: це та сама деталь продукту, тож і
 * розмітка, і стилі живуть у спільному коді (`packages/ui` + `.wb-composer*`
 * у `packages/shared/src/styles/components.css`). Оболонка лише відкриває
 * його — див. `withPrimaryAction` у `@wwwuabot/ui/nav`.
 *
 * @module @wwwuabot/ui/composer
 */

import type { ReactNode } from "react";
import type { IconName } from "@wwwuabot/shared";
import type { AdDraft } from "@wwwuabot/shared/ads";
import type { NoteDraft } from "@wwwuabot/shared/notes";
import type { PageDraft } from "@wwwuabot/shared/pages";

/**
 * Вкладка композера.
 *
 * `status` — це чесність, а не оформлення: `soon` означає, що під вкладкою
 * ще немає інтерфейсу, і вона показує, що там буде. Так само чесно поводиться
 * пункт футера без адреси (§7): краще сказати, ніж мовчки нічого не робити.
 */
export interface ComposerTab {
  /** Стабільний ключ React-списку й перемикання вкладок. */
  key: string;
  /** Підпис на вкладці. */
  label: string;
  /** Іконка з реєстру `@wwwuabot/shared`. */
  icon: IconName;
  /** `ready` — інтерфейс працює; `soon` — заглушка. */
  status: "ready" | "soon";
  /** Що саме тут буде — текст заглушки. */
  hint?: string;
  /** Пункти, які вкладка матиме: заглушка показує їх списком. */
  planned?: readonly string[];
}

export interface ComposerModalProps {
  /** Закрити композер. Відкриває й закриває його оболонка. */
  onClose: () => void;
  /**
   * Зберегти нотатку. Куди саме — знає **оболонка**, і це не дрібниця: у
   * платформі нотатка належить людині (ідентичність із підписаного `initData`),
   * у панелі — проєкту (акаунт cookie-сесії). Композер спільний, тож адреси
   * API в ньому немає; він віддає чернетку й чекає на помилку-кидок.
   */
  onSaveNote: (draft: NoteDraft) => Promise<void>;
  /**
   * Чернетка, з якої почати. `id` — означає «редагуємо існуючу нотатку»,
   * тож композер і заголовок міняє («Редагувати»), і `id` у збереженні.
   *
   * Чому той самий композер, а не окремий редактор: нотатка — ті самі два
   * поля й та сама стеля довжини. Друга форма для того самого мусила б
   * повторити і хештеги, і ріст поля, і — рано чи пізно — розійшлася б із
   * першою.
   */
  initial?: NoteDraft;
  /**
   * Зберегти оголошення. **Немає обробника — немає й вкладки**: дошка живе
   * тільки в платформі, і показувати в панелі форму, яка не вміє зберігати,
   * було б порожнім пунктом (AGENTS.md §7).
   */
  onSaveAd?: (draft: AdDraft) => Promise<void>;
  /** Чернетка оголошення: `id` — правка свого (дошка відкриває композер так). */
  initialAd?: AdDraft;
  /**
   * Зберегти сторінку. **Немає обробника — немає й вкладки**: сторінки
   * створюються в платформі, і показувати в панелі форму, яка не вміє
   *   зберігати, було б порожнім пунктом (AGENTS.md §7).
   */
  onSavePage?: (draft: PageDraft) => Promise<void>;
  /** Чернетка сторінки: `id` — правка своєї (список відкриває композер так). */
  initialPage?: PageDraft;
  /** Вкладка, з якої відкрити: дошка кличе композер саме на «Оголошення». */
  initialTab?: string;
}

/** Види вкладень, місце під які вже позначене. */
export type AttachmentKind = "photo" | "video" | "file";

/** Те, з чим працює вкладка «Нотатка»: текст, хештеги, вставка й вкладення. */
export interface ComposerNoteTabProps {
  note: string;
  onNoteChange: (value: string) => void;
  /**
   * Хештеги нотатки. Другий бік нотатки поруч із текстом: саме за ними її
   * потім знайдуть, тож вони зберігаються разом із текстом, а не окремо.
   */
  tags: readonly string[];
  /** Додати хештеги з довільного рядка (розбір і стелі — у `tags.ts`). */
  onAddTag: (raw: string) => void;
  onRemoveTag: (tag: string) => void;
  /** Вставити текст із буфера обміну. */
  onPaste: () => void;
  /** Додати вкладення — окрема тема, поки лише заглушка. */
  onAttach: (kind: AttachmentKind) => void;
  /** Помилка вставки (буфер недоступний). */
  error: string | null;
  /**
   * Кнопки дії вкладки. Вони живуть у **тілі** (останній рядок панелі), а не
   * в прибитому футері: кнопок буде більше, ніж дві, а фіксована смуга
   * забирала б місце в полів. Хто саме ці кнопки — знає композер (він тримає
   * `save` і стан збереження); вкладка лише ставить їх у свій розклад
   * (`.wb-sheet-actions` — спільний кирпичик повноекранних поверхонь).
   */
  actions?: ReactNode;
}
