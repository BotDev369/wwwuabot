/**
 * Типи поверхні зі списком пунктів — аркуш над скримом (`MenuModal`).
 *
 * Це та сама пара «склад ↔ розмітка», що у футера (`@wwwuabot/ui/nav`):
 * **склад** пунктів знає оболонка (у платформи — розділи хабу профілю),
 * а **вигляд і поведінка** — спільні, тож обидві оболонки отримують однакову
 * деталь. Композер (`@wwwuabot/ui/composer`) — сусідній випадок тієї ж
 * поверхні: там усередині вкладки, тут — список.
 *
 * Сам список (`MenuList`) рендериться і **без** поверхні: сторінка платформи
 * показує ті самі пункти в потоці, а не в аркуші — тож розмітка пункту одна,
 * а поверхня лише додає їй рамку, шапку й вихід.
 *
 * @module @wwwuabot/ui/menu
 */

import type { ReactNode } from "react";
import type { IconName } from "@wwwuabot/shared";

/**
 * Пункт меню в описі оболонки.
 *
 * `href` немає — пункт або заглушка, або дія: екрана під ним ще немає, і
 * оболонка сама вирішує, що показати на дотик (спільний `useDialog`).
 */
export interface ShellMenuItem {
  /** Стабільний ключ React-списку. */
  key: string;
  /** Підпис пункту. */
  label: string;
  /**
   * Іконка з реєстру `@wwwuabot/shared`. Немає — у пункту немає знака.
   *
   * Знак — це **керування**, а не вміст: пункти хабу профілю, панель розділів
   * і футер його мають (там він заміняє читання підпису), а рядки контенту
   * Простору — ні: назва гри, сторінки чи оголошення називає себе сама, і знак
   * перед нею був би ще одним підписом того самого (правило 23). Тому поле не
   * обов'язкове: мовчазна іконка-заглушка тут була б гіршою за відсутність.
   */
  icon?: IconName;
  /** Адреса пункту. Немає — заглушка або своя дія. */
  href?: string;
  /** Своя дія замість навігації: панель усередині тієї ж модалки, перемикач. */
  onSelect?: () => void;
  /**
   * `ready` — під пунктом справжній екран; `soon` — його ще немає.
   *
   * Це чесність, а не оформлення (§7): пункт, який мовчки нічого не робить,
   * гірший за чесне «ще не зроблено». Типове значення — `ready`, бо
   * більшість пунктів ведуть на існуючий екран.
   */
  status?: "ready" | "soon";
  /**
   * Що саме буде в пункті, якого ще немає.
   *
   * Видно по-різному, і це навмисно: у рядку пояснення стоїть під підписом
   * (там його читають), а в плитці замість нього — чип «Скоро», бо абзац
   * робив плитки різної висоти. В обох випадках текст іде в підпис кнопки,
   * і він же — те, що показує діалог після дотику.
   */
  hint?: string;
  /**
   * Пункт — один із варіантів вибору, і вибраний саме він: вибір малює галочку,
   * бо він стан, а не перехід. Ним користуються списки вибору (вигляд
   * колекції, сортування, групування, теги).
   */
  selected?: boolean;
  /**
   * Пункт **веде далі** — і це видно шевроном праворуч.
   *
   * Ознака саме переходу, а не важливості: рядок, за яким стоїть екран (гра,
   * сторінка людини, чужа сторінка), шеврон має, а той, що діє на місці
   * (тема застосовується кнопкою, оголошення нікуди не веде), — ні. Мовчазне
   * «десь є, десь немає» читалось як два різні типи рядків (§9).
   */
  trailing?: boolean;
}

/** Пункт, готовий до рендерингу: дотик завжди щось робить. */
export interface MenuItem extends ShellMenuItem {
  onSelect: () => void;
}

/**
 * Як розкласти пункти: `rows` — рядок на всю ширину (типове), `blocks` —
 * «плитки» по дві в ряду.
 *
 * Це не оформлення, а різниця ролі: у списку пункти **читають** (вибір
 * одного з багатьох: вигляд колекції, теги), у плитках — **тицяють**
 * (розділи хабу профілю, де напис знають напам'ять). Вибір лишається за
 * оболонкою: друга розкладка під ту саму роль — це вже два списки.
 */
export type MenuLayout = "rows" | "blocks";

export interface MenuModalProps {
  /** Заголовок модалки (`aria-label` — теж він). */
  title: string;
  /** Пункти у порядку показу — згори вниз. Немає — поверхня показує `content`. */
  items?: readonly MenuItem[];
  /** Розкладка пунктів — див. `MenuLayout`. */
  layout?: MenuLayout;
  /**
   * Вміст **замість** списку пунктів: так форма контакту і форма нового листа
   * потрапляють у ту саму поверхню, не стаючи другою модалкою над першою.
   *
   * Саме «замість», а не «додатково»: два способи показати один список — це
   * два різні списки вже на наступній правці.
   */
  content?: ReactNode;
  /**
   * Блок над списком — те, що не є пунктом: пояснення до вибору чи
   * заголовок розділу. «Хто це» сюди не потрапляє: людина бачить себе на
   * своєму екрані (`UserProfileCard`), а другий опис того самого факту
   * розійшовся б із першим.
   *
   * Саме `ReactNode`, а не готовий «профіль»: ця поверхня спільна, і знати
   * про Telegram-ідентичність їй нема чого — її дає оболонка.
   */
  header?: ReactNode;
  /** Закрити меню. Відкриває й закриває його оболонка. */
  onClose: () => void;
}
