/**
 * Типи «хабу» — списку, у кожного пункту якого **дві дії**.
 *
 * Це не меню (`@wwwuabot/ui/menu`) і не колекція (`@wwwuabot/ui/collection`):
 * у меню дотик до пункту робить одне, у колекції пункт читають, а тут пункт
 * **обирають дією** — «подивитись» або «створити». Тому підпис пункту не є
 * кнопкою: дію називає знак праворуч, а не місце, куди влучив палець.
 *
 * Склад пунктів знає оболонка (у платформи — хаб «Створити»), а вигляд і
 * розкладку — цей кирпичик: та сама пара «склад ↔ розмітка», що у футера й
 * меню.
 *
 * @module @wwwuabot/ui/hub
 */

import type { IconName } from "@wwwuabot/shared";
import type { MenuLayout } from "../menu/types";

/**
 * Дія пункту — кнопка зі знаком без підпису.
 *
 * Підпису в кнопки немає: у ряду їх дві, і два слова («Переглянути» +
 * «Створити») розтягнули б рядок, який читають заради назви. Слово лишається
 * в `label` — воно йде в `aria-label`, тож без знака кнопка не лишається
 * безіменною.
 */
export interface HubAction {
  /** Стабільний ключ React-списку. */
  key: string;
  /** Ім'я дії для скрінрідера — те, що робить знак. */
  label: string;
  /** Іконка з реєстру `@wwwuabot/shared`. */
  icon: IconName;
  /**
   * За дією ще нічого немає: знак приглушений, а дотик чесно каже, що там
   * буде. Це не оформлення, а стан (§7): кнопка, яка мовчки нічого не робить,
   * гірша за чесну відмову.
   */
  soon?: boolean;
  onSelect: () => void;
}

/** Пункт хабу: назва, знак і дві (чи більше) дії праворуч. */
export interface HubItem {
  /** Стабільний ключ React-списку. */
  key: string;
  /** Підпис пункту. */
  label: string;
  /** Іконка з реєстру `@wwwuabot/shared`. */
  icon: IconName;
  /**
   * `ready` — за пунктом є екран; `soon` — немає жодної робочої дії.
   *
   * Типове значення — `ready`, бо більшість пунктів працюють; `soon` каже
   * про себе ще до дотику (приглушений підпис, а в плитці — чип).
   */
  status?: "ready" | "soon";
  /** Що саме буде — тільки в пункту, якого ще немає. */
  hint?: string;
  /** Дії пункту — у порядку показу, праворуч від підписа. */
  actions: readonly HubAction[];
}

export interface HubListProps {
  items: readonly HubItem[];
  /** Розкладка — та сама пара, що в меню: рядок читають, у плитку тицяють. */
  layout?: MenuLayout;
}
