/**
 * Типи повідомлень: склад дає оболонка, вигляд спільний.
 *
 * Та сама пара «склад ↔ розмітка», що в нотатках і контактах: **дані** й дії
 * (`onSend`, `onOpen`) приходять від оболонки, а як це виглядає й поводиться —
 * спільне. Друга копія розмітки в другій оболонці розійшлася б із першою на
 * першій же правці — саме тому це кирпичик, а не «стиль оболонки».
 *
 * **Вигляд списку тут — не склад екрана.** Пошук, фільтр, порядок, групи й
 * розкладку описує `MessagesView`, а `view.ts` перетворює `Conversation[]` +
 * цей вигляд у групи для рендеру — тому всі правила можна перевірити без DOM.
 *
 * @module @wwwuabot/ui/messages
 */

import type { Conversation, Message, MessageDraft, MessagePeer } from "@wwwuabot/shared/messages";
import type {
  CollectionChip,
  CollectionColumns,
  CollectionLayout,
  CollectionView,
} from "../collection";

/**
 * Порядок показу розмов.
 *
 * Типовий — за останнім повідомленням: у листування заходять, щоб побачити те,
 * що сталося щойно, і жоден інший порядок цього не дає. «За іменем» потрібен,
 * коли шукають **конкретну людину**, а «непрочитані спершу» — коли розмов
 * багато і в них загубилось те, на що не відповіли.
 */
export type MessagesSort = "recent" | "unread" | "name";

/** За чим збирати розмови в групи. */
export type MessagesGroupBy = "none" | "day";

/**
 * Що саме показувати зі списку.
 *
 * Це **фільтр**, а не порядок: «без повідомлень» — не «порожні згори», а
 * «покажи лише ті, де ще нічого не сказано» (з них починають нові розмови).
 */
export type MessagesFilter = "all" | "unread" | "empty";

/** Те, що людина вибрала у смузі керування. */
export interface MessagesView {
  /** Пошук за іменем, хендлом і текстом останнього повідомлення. */
  query: string;
  filter: MessagesFilter;
  sort: MessagesSort;
  groupBy: MessagesGroupBy;
  /** Рядки чи плитки — стан екрана, а не списку. */
  layout: CollectionLayout;
  /** Скільком колонками стоять плитки. У рядків значення немає. */
  columns: CollectionColumns;
}

/**
 * Типовий вигляд.
 *
 * **Груп типово немає** — як у нотатках і контактах: список розмов і без них
 * упорядкований за часом, а «Сьогодні / Вчора» ріжуть його рівно тоді, коли
 * розмов справді багато. Групування лишається вибором у смузі.
 */
export const DEFAULT_MESSAGES_VIEW: MessagesView = {
  query: "",
  filter: "all",
  sort: "recent",
  groupBy: "none",
  layout: "rows",
  columns: 2,
};

/** Чип смуги керування — те, що людина вибрала, і як це зняти. */
export type MessagesChip = CollectionChip<MessagesView>;

/**
 * Група в списку — з неї рендериться заголовок і рядки.
 *
 * У заголовку стоїть **кількість розмов**: це те, як список розклали, а не ще
 * одне число лійки.
 */
export interface MessagesGroup {
  /** Стабільний ключ React-списку (`day:today`, `none`). */
  key: string;
  /** Підпис групи. */
  label: string;
  conversations: Conversation[];
}

export interface ConversationListProps {
  /** Групи — список уже відфільтрований і складений (`buildConversationGroups`). */
  groups: readonly MessagesGroup[];
  /** Скільки розмов узагалі: щоб різнити «немає з ким» від «нічого не знайшлось». */
  total: number;
  /** Хто я — потрібно, щоб позначити **своє** в рядку («Ви: …»). */
  meId: number;
  /** Відкрити розмову зі співрозмовником. */
  onOpen: (peerId: number) => void;
  /** Рядки чи плитки — стан екрана, а не списку. */
  collection: CollectionView;
  /** Скинути пошук і фільтри — потрібен стану «нічого не знайдено». */
  onReset?: () => void;
}

export interface ThreadSheetProps {
  /** Співрозмовник; `null` — ще не знаємо, бо стрічка не прийшла. */
  peer: MessagePeer | null;
  /** Хто я: бульбашка праворуч — моя, ліворуч — чужа. */
  meId: number;
  messages: readonly Message[];
  loading?: boolean;
  error?: string | null;
  sending?: boolean;
  /**
   * Надіслати текст; порожнє поле цього не робить.
   *
   * `true` означає, що сервер підтвердив надсилання — лише тоді поле вводу
   * чиститься. Порожнє поле після невдачі виглядало б як успіх і коштувало б
   * людини втраченого тексту.
   */
  onSend: (body: string) => Promise<boolean>;
  /**
   * Стерти переписку — у обох: рядок переписки один на пару.
   *
   * Поверхня лише каже, що людину покликали: чи питати підтвердження й кого
   * саме — вирішує оболонка (як з `onSend` і `onOpen`). Це не формальність:
   * дія незворотна, а `window.confirm` у Telegram Mini App на iOS не існує (§4),
   * тож підтвердження мусить бути спільним діалогом (`useDialog`).
   */
  onClear: () => void;
  /**
   * Прибрати розмову зі списку.
   *
   * Історія при цьому стирається в обох, а сама розмова ховається в того, хто
   * прибрав: у співрозмовника вона лишається, і нове повідомлення вертає її
   * обом — інакше прибрана розмова не мала б жодного шляху назад.
   */
  onDelete: () => void;
  onClose: () => void;
}

export interface MessagesToolbarProps {
  view: MessagesView;
  onChange: (patch: Partial<MessagesView>) => void;
  /** Скільки розмов видно зараз і скільки всього. */
  shown: number;
  total: number;
  /**
   * Почати нове повідомлення — вибрати, кому писати.
   *
   * Саме «кому», а не «що»: написати можна лише тому, з ким людина зв'язана
   * через контакти, тож дія відкриває вибір співрозмовника, а не порожній
   * аркуш без адресата.
   */
  onNew: () => void;
}

export interface NewMessagePickerProps {
  /**
   * Усі, кому можна писати.
   *
   * Перелік дає сервер (`/api/messages/compose`), і це **зв'язані через
   * контакти** — разом із тими, чию розмову прибрано зі списку: прибрати
   * розмову не означає «заборонити писати». Порядок приходить готовий (за
   * іменем), тож тут його ніхто не переставляє другим правилом.
   */
  recipients: readonly MessagePeer[];
  /** Обрали людину — форма бере її собі. */
  onSelect: (peerId: number) => void;
  onClose: () => void;
}

/**
 * Форма нового повідомлення: **кому** і **тіло**.
 *
 * Це та сама повноекранна поверхня, що форма контакту (`MenuModal`): поля в
 * тілі, дії — рядком унизу. Надіслати й зберегти чернетку — **дві різні дії**, і
 * обидві закривають форму: результат у них однаковий — «не надіслано, але
 * збережено» і «надіслано».
 *
 * Самого надсилання форма не робить: це справа оболонки (як у розмові) — вона ж
 * веде стан, показує помилку й вирішує, що відкрити після відправки.
 */
export interface NewMessageSheetProps {
  /** Кому можна писати — той самий перелік, що у виборі людини. */
  recipients: readonly MessagePeer[];
  /** Збережені чернетки: найсвіжіша відкриває форму, решта — за адресатом. */
  drafts: readonly MessageDraft[];
  /** Зберегти чернетку; `true` — сервер підтвердив. */
  onSaveDraft: (peerId: number, body: string) => Promise<boolean>;
  /** Надіслати; `true` — сервер підтвердив. */
  onSend: (peerId: number, body: string) => Promise<boolean>;
  onClose: () => void;
}
