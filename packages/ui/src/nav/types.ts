/**
 * Типи глобального нижнього футера.
 *
 * Футер — спільна деталь обох оболонок (AGENTS.md §3), а отже його розмітка
 * однакова, а різниться лише СКЛАД пунктів: у платформи — сторінки вебу,
 * в адмінці — розділи панелі. Це те саме правило, що й для меню.
 *
 * @module @wwwuabot/ui/nav
 */

import type { IconName } from "@wwwuabot/shared";

/**
 * Пункт футера в описі оболонки.
 *
 * `href` немає — пункт-заглушка: екрана під ним ще немає, і оболонка сама
 * вирішує, що показати на дотик (спільний `useDialog`).
 */
export interface ShellTab {
  /** Стабільний ключ React-списку. */
  key: string;
  /** Підпис під іконкою. */
  label: string;
  /** Іконка з реєстру `@wwwuabot/shared` — контурна, для невибраного пункту. */
  icon: IconName;
  /**
   * Залитий варіант тієї самої іконки — для вибраного пункту.
   *
   * Патерн топових застосунків: активний розділ виділяє сам знак (контур →
   * заливка), а не фон під ним. Немає — активний стан показує лише колір
   * і жирніший штрих.
   */
  iconActive?: IconName;
  /** Адреса пункту. Немає — заглушка. */
  href?: string;
  /**
   * Центральний слот дії («+»): іконка без підпису.
   *
   * Ні тла, ні акцентного кольору в нього немає — видно його за місцем у смузі
   * (центр) і трохи товщим штрихом. Акцент у смузі означає «тут ти», тобто
   * рівно один пункт — вибраний розділ, а «+» видно завжди.
   */
  primary?: boolean;
  /**
   * Своя дія замість навігації — те, чого футер не знає.
   *
   * Знадобилось центральному «+»: він відкриває композер
   * (`@wwwuabot/ui/composer`), а не веде на адресу — «створити» це дія, а не
   * розділ, і сторінки під нею не існує. Без цього поля оболонка мусила б
   * тримати другу смугу футера лише заради однієї кнопки.
   */
  onSelect?: () => void;
}

/** Пункт футера, готовий до рендерингу. */
export interface TabBarItem extends ShellTab {
  /** Пункт відповідає поточній адресі. */
  active?: boolean;
}
