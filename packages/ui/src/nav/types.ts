/**
 * Типи глобального нижнього футера.
 *
 * Футер — спільна деталь обох оболонок (AGENTS.md §3), а отже його розмітка
 * однакова, а різниться лише СКЛАД пунктів: у платформи — сторінки вебу,
 * в адмінці — розділи панелі. Це те саме правило, що й для меню.
 *
 * @module @wwwuabot/ui/nav
 */

import type { ReactNode } from "react";
import type { IconName } from "@wwwuabot/shared";

/**
 * Пункт футера в описі оболонки.
 *
 * `href` немає — пункт-заглушка: екрана під ним ще немає, і оболонка сама
 * вирішує, що показати на дотик (спільний `useDialog`).
 */
export interface ShellTab {
  /** Стабільний ключ React-списку. */
  key: string;
  /** Підпис під іконкою. */
  label: string;
  /** Іконка з реєстру `@wwwuabot/shared` — контурна, для невибраного пункту. */
  icon: IconName;
  /**
   * Залитий варіант тієї самої іконки — для вибраного пункту.
   *
   * Патерн топових застосунків: активний розділ виділяє сам знак (контур →
   * заливка), а не фон під ним. Немає — активний стан показує лише колір
   * і жирніший штрих.
   */
  iconActive?: IconName;
  /** Адреса пункту. Немає — заглушка. */
  href?: string;
  /**
   * Центральний слот дії («+»): іконка без підпису.
   *
   * Ні тла, ні акцентного кольору в нього немає — видно його за місцем у смузі
   * (центр) і трохи товщим штрихом. Акцент у смузі означає «тут ти», тобто
   * рівно один пункт — вибраний розділ, а «+» видно завжди.
   */
  primary?: boolean;
  /**
   * Скільком подіям пункт чекає — число на іконці (лише коли воно є).
   *
   * Потрібно «Повідомленням»: у Mini App пушів немає (Telegram WebView не дає
   * Push API), тож єдине, чим платформа може сказати про нове, — сама смуга,
   * поки людина в застосунку. Немає числа — немає й знака: нуль на іконці
   * читався б як «щось є». */
  badge?: number;
  /**
   * Своя дія замість навігації — те, чого футер не знає.
   *
   * Знадобилось центральному «+»: він відкриває композер
   * (`@wwwuabot/ui/composer`), а не веде на адресу — «створити» це дія, а не
   * розділ, і сторінки під нею не існує. Без цього поля оболонка мусила б
   * тримати другу смугу футера лише заради однієї кнопки.
   */
  onSelect?: () => void;
}

/** Пункт футера, готовий до рендерингу. */
export interface TabBarItem extends ShellTab {
  /** Пункт відповідає поточній адресі. */
  active?: boolean;
}

/**
 * Пункт **другого** футера (`SubBar`) — смуги над головною.
 *
 * Ознак тут менше, ніж у пункту футера, і це не спрощення: друга смуга —
 * навігація **всередині одного розділу** (вибір шрифту, кольорів, бібліотек),
 * тож у неї немає ні центрального слота дії, ні числа подій. Склад, як і в
 * футера, знає оболонка; розмітку — кирпичик.
 */
export interface ShellSubItem {
  key: string;
  label: string;
  icon: IconName;
  /** Адреса пункту. Немає — заглушка: оболонка вирішує, що показати на дотик. */
  href?: string;
  /** Своя дія замість навігації — те, чого смуга не знає. */
  onSelect?: () => void;
}

/** Пункт другої смуги, готовий до рендерингу. */
export interface SubBarItem extends ShellSubItem {
  /** Пункт відповідає поточній адресі. */
  active?: boolean;
}

/**
 * Пункт **сайдбара** (`SideBar`) — єдиний для меню адмінки, панелі розділів
 * Простору й списку розділів теми.
 *
 * Ознак тут більше, ніж у пункту футера, і це не «на всяк випадок»: сайдбар
 * показує не лише назву розділу, а й **стан** під нею (розділи теми кажуть
 * «Apple», назву теми чи шрифт) і **ознаку переходу** (шеврон). Обидві риси вже
 * були в продукті — але тільки в розділів теми, де для них існував окремий
 * набір класів; тепер вони властиві самому пункту, тож будь-який сайдбар може
 * їх ужити, не малюючи собі другого вигляду.
 */
export interface SideBarItem {
  /** Стабільний ключ React-списку. */
  key: string;
  /** Підпис пункту. */
  label: string;
  /** Знак пункту: у згорнутому сайдбарі він лишається сам. */
  icon: IconName;
  /** Другий рядок пункту — **стан**, а не пояснення («Apple», назва теми). */
  hint?: ReactNode;
  /** Знак у кінці рядка: за пунктом стоїть екран, а не дія. */
  more?: boolean;
  /** Адреса пункту. Разом із `navigate` — перехід у межах SPA. */
  href?: string;
  /** Своя дія замість навігації. */
  onSelect?: () => void;
  /** Пункт відповідає поточному екрану. */
  active?: boolean;
  /**
   * Роль пункту, коли смуга — не список посилань: `tab` — вкладки Простору,
   * `radio` — вибір (характер продукту в розділах теми).
   */
  role?: "tab" | "radio";
  /** `id` пункту (вкладки: пара з `panelId` — те саме, що в `@wwwuabot/ui/tabs`). */
  id?: string;
  /** `id` панели, яку пункт відкриває. */
  panelId?: string;
}

/** Секція сайдбара: підпис над групою пунктів. */
export interface SideBarSection {
  key: string;
  /** Заголовок секції — є не в усіх (у Просторі розділ один). */
  title?: string;
  items: readonly SideBarItem[];
}
