/**
 * Підсумкові числа контактів — три пари «знак + число» в шапці екрана.
 *
 * Список відповідає на питання «хто в мене є», а числа — на «що з цього
 * вийшло»: скільки контактів узагалі, скільки людей зайшло **в бота** й
 * скільки дійшло **до платформи**. Останній крок і є тим, що відрізняє часткове
 * приєднання від повного.
 *
 * **Знак, а не плашка й не підпис.** Числа читають **порівнюючи**, і для цього
 * досить трьох знаків поруч: заливка з підписом унизу важила б більше за саму
 * цифру, а в шапці місце належить назві екрана. Слово з розмітки **не зникло** —
 * воно лишилось у `dt` і сховане: око бачить знак, а скрінрідер читає «Всього 2»,
 * бо сама іконка нічого не називає. Знаки різні навмисно (`users` / `bot` /
 * `globe`) — три однакові силуети читались би як одне число.
 *
 * **Усе акцентом.** Це підсумок, а не примітка: акцент тут — той самий, що в
 * головної дії поруч, і саме він робить числа видимими в шапці.
 *
 * **Це не три назви одного.** «Всього ≥ Бот ≥ Платформа» — лійка, і кожен крок
 * менший за попередній: людина може зайти в бота й не відкрити Mini App, а
 * контакт може лежати в довіднику взагалі без лінка. Друге джерело для чисел не
 * потрібне — вони рахуються з тих самих контактів (`contactStats`), бо це той
 * самий факт під іншим кутом.
 *
 * **Числа — про людей, записи — про власника.** Два лінки на ту саму людину
 * дають два записи й **одну** людину в «у боті». Рядка-пояснення під числами
 * немає навмисно: різницю видно там, де вона й виникає — у списку, де другий
 * запис підписаний «та сама людина, що …». Числа без пояснення не брешуть:
 * «всього» рахує **усі** записи, а не лише запрошені.
 *
 * Числа стоять **у шапці, у ряд із назвою**, а не блоком під нею чи під списком:
 * блок відсував би їх від заголовка — за ними треба було б прокручувати рівно
 * тоді, коли список довгий, а питають про них саме тоді.
 *
 * @module @wwwuabot/ui/contacts
 */

import type { ReactElement } from "react";
import { Icon, type IconName } from "@wwwuabot/shared";
import type { Contact } from "@wwwuabot/shared/contacts";
import { contactStats, type ContactStats } from "./scheme";

interface Step {
  /** Знак, який «каже» замість слова: люди / бот / платформа. */
  icon: IconName;
  /** Слово для скрінрідера (і підказка на десктопі) — на екрані його немає. */
  label: string;
  value: (stats: ContactStats) => number;
}

/** Три кроки лійки — у тому порядку, у якому їх читають: за спаданням. */
const STEPS: readonly Step[] = [
  { icon: "users", label: "Всього", value: (stats) => stats.total },
  { icon: "bot", label: "Бот", value: (stats) => stats.bot },
  { icon: "globe", label: "Платформа", value: (stats) => stats.platform },
];

export function ContactTotals({ contacts }: { contacts: readonly Contact[] }): ReactElement {
  const stats = contactStats(contacts);

  return (
    <dl className="wb-contact-stats">
      {STEPS.map((step) => (
        <div className="wb-contact-stat" key={step.label} title={step.label}>
          <dt className="wb-contact-stat-label">
            <Icon name={step.icon} size={16} />
            <span className="wb-contact-stat-word">{step.label}</span>
          </dt>
          <dd className="wb-contact-stat-value">{step.value(stats)}</dd>
        </div>
      ))}
    </dl>
  );
}
