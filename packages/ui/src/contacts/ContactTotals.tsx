/**
 * Підсумкові числа контактів — те, заради чого лінк і існує.
 *
 * Список відповідає на питання «хто в мене є», а числа — на «що з цього
 * вийшло»: скільком склали лінк, скільки людей зайшло **в бота** й скільки
 * дійшло **до платформи**. Останній крок і є тим, що відрізняє часткове
 * приєднання від повного.
 *
 * **Це не три назви одного.** «Запрошено / у боті / на платформі» — лійка, і
 * кожен крок менший за попередній: людина може зайти в бота й не відкрити
 * Mini App. Друге джерело для чисел не потрібне — вони рахуються з тих самих
 * контактів (`contactStats`), бо це той самий факт під іншим кутом.
 *
 * **Числа стоять у шапці, а не окремим блоком.** Блок «схема залучених» унизу
 * екрана відсував числа від заголовка: за ними треба було прокручувати рівно
 * тоді, коли список довгий, — а питають про них саме тоді. Тому вони компактні
 * й стоять поруч із назвою екрана.
 *
 * **Числа — про людей, записи — про власника.** Два лінки на ту саму людину
 * дають два записи й **одну** людину в лійці; тому під числами стоїть
 * рядок-пояснення — без нього «запрошено 2 → у боті 1» читалось би як діра в
 * рахунку, хоч це правда.
 *
 * @module @wwwuabot/ui/contacts
 */

import type { ReactElement } from "react";
import type { Contact } from "@wwwuabot/shared/contacts";
import { contactStats, recordWord } from "./scheme";

export function ContactTotals({ contacts }: { contacts: readonly Contact[] }): ReactElement {
  const stats = contactStats(contacts);

  return (
    <div className="wb-contact-totals">
      <dl className="wb-contact-stats">
        <div className="wb-contact-stat">
          <dt>Запрошено</dt>
          <dd>{stats.invited}</dd>
        </div>
        <div className="wb-contact-stat">
          <dt>У боті</dt>
          <dd>{stats.bot}</dd>
        </div>
        <div className="wb-contact-stat">
          <dt>На платформі</dt>
          <dd>{stats.platform}</dd>
        </div>
      </dl>

      {/* Чому число менше за попереднє — сказано тут, а не в голові власника:
          дублі не помилка, вони просто не подвоюють людину. */}
      {stats.duplicates > 0 && (
        <p className="wb-contact-twins-note">
          Ще {recordWord(stats.duplicates)} про тих самих людей: у числах кожна людина порахована
          один раз.
        </p>
      )}
    </div>
  );
}
