/**
 * WHO-5 Well-Being Index — індекс благополуччя Всесвітньої організації охорони
 * здоров'я. П'ять тверджень, шкала 0–5, сума множиться на 4 (0–100).
 *
 * **Чому саме він, а не опитувальник тривожності.** У HADS два з чотирнадцяти
 * питань рахуються **у протилежний бік** («Я відчуваю себе розслабленим» — не
 * те саме, що «Я відчуваю напругу»), і переплутаний напрямок дає людині
 * неправильний бал на рівні діагнозу. У WHO-5 **усі п'ять рахуються однаково**,
 * тому неточність перекладу змінює красоту слова, а не число. Для розділу
 * «Розвиток» це принципово різний рівень ризику.
 *
 * **Тон теж має значення.** Це не скринінг депресії, а вимір того, наскільки
 * людині добре. Питання позитивні, тож результат не називає людину хворою.
 *
 * **Що тут підтверджено, а що — наше рішення.** Підтверджено джерелами: п'ять
 * питань, шкала 0–5, сума × 4, поріг **50** (Topp et al., 2015) і значуща
 * зміна **10%** (документ ВОЗ Європа). **Межі верхніх смуг — наше рішення про
 * те, як говорити з людиною**: у джерелах вони розходяться (50–75 чи 50–69), тож
 * вигадувати «офіційні» межі не можна. Вивід керує **поріг 50**, а не смуги.
 *
 * **Переклад — чернетка.** Офіційної української версії ВОЗ немає (у списку
 * мов ВОЗ її не значить). Джерелом є адаптація **Л. М. Карамушки, К. В. Терещенко,
 * О. В. Креденце** — стандарт української психології; звірити формулювання
 * треба з оригіналом Карамушки. На бал це не впливає (усі питання одного
 * напрямку), тільки на те, як текст читається.
 *
 * @module @wwwuabot/shared/assessments/who5
 */

