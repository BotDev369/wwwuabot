/**
 * Спільний висновок за двома шкалами одного тесту (§7.5).
 *
 * **Живе тут, а не на екрані списку.** Коли PHQ-9 і GAD-7 були двома тестами,
 * «Разом за двома шкалами» довелося показувати на сторінці «Розвиток» — і
 * власник 29.09.2026 сказав, що там мають бути тільки картки тестів. Тепер
 * обидва бали живуть **в одному проходженні**, тож висновок з'являється там, де
 * й його дані: на картці результату, після обох шкал.
 *
 * **Шість комбінацій, а не одна формула.** «Тривога переважає» й «обидва разом»
 * — це різні відповіді людині, і обидві мають власний текст. Порядок перевірки
 * заданий специфікацією (зверху вниз, перша відповідність), тому сума ≥ 10 в
 * обох перевіряється **раніше**, ніж «легкі прояви обох станів» — інакше людина
 * з 12 і 11 прочитала б заспокійливе.
 *
 * @module @wwwuabot/shared/assessments/combined
 */

/** Яка з шести комбінацій §7.5. */
export type CombinedKey =
  "comorbid" | "mood-dominant" | "anxiety-dominant" | "mild-both" | "low-both" | "border";

/**
 * Межа «помірних симптомів» — з §6.1 і §6.2.
 *
 * **Число, а не змінна з тесту.** Поріг уваги в шкалі — це «варто обговорити з
 * фахівцем», тобто межа, вище якої результат уже не «легкий». Для правила
 * «м'яко чи вже ні» це інша межа, і вона однакова для обох інструментів за
 * опублікованими шкалами.
 */
const MODERATE = 10;

/** Нижня межа «легких симптомів» за §6.1 і §6.2 — починається з п'яти. */
const MILD = 5;

/**
 * Яка з шести комбінацій §7.5.
 *
 * Аргументи — це сири результати обох шкал, у порядку шкал тесту.
 */
export function combinedKeyOf(firstRaw: number, secondRaw: number): CombinedKey {
  const firstPositive = firstRaw >= MODERATE;
  const secondPositive = secondRaw >= MODERATE;
  if (firstPositive && secondPositive) return "comorbid";
  if (firstPositive) return "mood-dominant";
  if (secondPositive) return "anxiety-dominant";
  if (firstRaw >= MILD && secondRaw >= MILD) return "mild-both";
  if (firstRaw < MILD && secondRaw < MILD) return "low-both";
  return "border";
}
