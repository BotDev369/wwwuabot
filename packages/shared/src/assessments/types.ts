/**
 * Типи самооцінки: тест, шкала, питання, смуга результату.
 *
 * **Тест — це дані, а не код.** Питання, варіантелі й межі смуг лежать
 * літералом у модулі тесту (`who5.ts`), а рахуванням займається одна чиста
 * функція (`score.ts`). Новий тест додається **файлом із даними**, а не
 * гілкою в розрахунку: інакше правило рахування розмножиться на два.
 *
 * **Тест може мати кілька шкал, і це не окремі тести.** «Тревожність і
 * депресія» — це одне проходження з двома блоками питань, кожен зі своїми
 * смугами, порогом і напрямком. Тому смуги, поріг і зміна живуть у шкалі
 * (`AssessmentScale`), а не в тесті: поки вони були в тесті, другий блок
 * мусив би мати власний тест, а людина — проходити два рази те, що
 * питає про один стан.
 *
 * **Бали рахує сервер.** Клієнт надсилає лише номери обраних варіантів, а
 * `scoreAssessment` живе в `@wwwuabot/shared` і викликається з `api-dev`.
 * Рахунок, який прийшов від клієнта, не приймається ніколи — тоді правило
 * рахування живе в одному місці, і людина не може підробити собі «нормальний»
 * результат.
 *
 * @module @wwwuabot/shared/assessments/types
 */

/** Один варіант відповіді: `value` — це бал у шкалі, `label` — що бачить людина. */
export interface ScaleOption {
  readonly value: number;
  readonly label: string;
}

/** Питання тесту. Текст без номера: порядок визначає масив `items`. */
export interface AssessmentItem {
  readonly id: string;
  readonly text: string;
  /**
   * Коротка назва сфери («Відпочинок»). Саме вона, а не текст питання,
   * потрібна людині, щоб зрозуміти, **де** її слабке місце: «20 з 25» нічого
   * не каже, а «відпочинок — 2 з 5» каже все.
   */
  readonly label: string;
  /**
   * Ключ шкали, до якої питання належить. **Питання без нього — спільне** для
   * всього тесту: так працює питання про вплив на життя, бо воно стосується
   * обох блоків одразу і не має смуг ані в одному з них.
   */
  readonly scale?: string;
  /**
   * Питання для роздумів, коли ця сфера найнижча. **Питання, а не порада й
   * не твердження про причину**: у нас немає жодного клінічного підґрунтя
   * стверджувати, чому в кого саме просів сон, і вигадана причина гірша за
   * чесне питання.
   */
  readonly weakNote?: string;
  /**
   * **Не входить у суму.** Так працює питання про вплив на життя: воно
   * міряє наслідок, а не симптом, тому бали за нього не нараховуються, але
   * відповідь зберігається й окремо показується.
   */
  readonly countsTowardScore?: boolean;
  /**
   * Поріг відповіді, за якого це питання вимагає окремої реакції: блоки
   * «Тревожність і депресія» показують персональний акцент на відповіді ≥ 2
   * («більше половини днів» і частіше). На відміну від `weakNote`, який
   * стосується лише найслабшої сфери, спрацьовує **кожне** питання, що
   * перевищило поріг.
   */
  readonly alertAtLeast?: number;
  readonly alertNote?: string;
  /**
   * **Питання безпеки.** Будь-яка відповідь вище нуля запускає протокол
   * допомоги — незалежно від загального балу. У PHQ-9 це питання 9 («думки
   * про те, що вам краще було б померти»), і людина з 2 балами з 27 мусить
   * отримати блок допомоги так само, як з 20.
   *
   * Тому це працює **поза смугами**: прапор safety не береться з `percent`
   * і не може бути придушеним низьким підсумком.
   */
  readonly safety?: boolean;
  /** Текст протоколу за рівнем відповіді: ключ — значення відповіді. */
  readonly safetyTexts?: Readonly<Record<number, string>>;
}

/**
 * Смуга результату — це **підпис до балу, а не діагноз**.
 *
 * **Межі — у балах тієї шкали, за яку людина відповідала.** Не у відсотках:
 * у PHQ-9 смуга 5–9 — це п'ять із 27 балів, а не 5% (тобто 1,35 бала). Коли
 * `min`/`max` вимірювалися у відсотках, а код порівнював їх із `percent`,
 * більшість сум **не потрапляли ні в одну смугу** і результат не зберігася
 * взагалі: 17 із 22 можливих сум GAD-7 і 20 із 28 сум PHQ-9 кидали помилку.
 *
 * Межі верхніх смуг — наше рішення про те, як розмовляти з людиною, а не
 * опублікована шкала ВОЗ: у джерелах вони розходяться. Єдине, що керує
 * виводом, — перевірений `attentionRaw`.
 */
export interface AssessmentBand {
  readonly key: string;
  readonly min: number;
  readonly max: number;
  readonly label: string;
  /** Пояснення для людини: що означає ця смуга, без медичних обіцянок. */
  readonly note: string;
}

/** Джерело інструменту: обов'язкове, бо вакцинація не анонімна і має авторів. */
export interface AssessmentSource {
  readonly name: string;
  readonly citation: string;
  readonly url: string;
  readonly license: string;
}

/**
 * **Шкала — це блок питань разом із власною смугою.** Тест, у якому їх дві,
 * має дві шкали; тест з однією — одну. Атрибути смуг живуть тут, а не в
 * тесті, бо інакше другий блок приречений на власний тест — тобто на подвійне
 * проходження й подвійний бал у базі.
 */
export interface AssessmentScale {
  /** Ключ шкали: ним питання (`item.scale`) і рядок результату посилаються. */
  readonly key: string;
  /** Назва блока для людини: «Настрій і депресія», «Тривога». */
  readonly title: string;
  /** Одне речення про те, що міряє цей блок — показується на початку блока. */
  readonly lead: string;
  readonly bands: readonly AssessmentBand[];
  /**
   * Межа уваги — **у балах шкали**, у тій самій одиниці, що й смуги.
   *
   * Для WHO-5 це 12 з 25, тобто 48% — найближча досяжна сума до підтвердженого
   * порогу 50 зі 100 (Topp et al., 2015). Для шкал симптомів це 10 — та сама
   * опублікована межа, але вона завжди була в балах, і саме в балах її
   * порівнює `exceedsAttention`.
   */
  readonly attentionRaw: number;
  /**
   * **У який бік шкали гірше.** Поле обовʼязкове, бо шкали ростуть у
   * протилежні боки: у WHO-5 відсутність тривоги це добре, а в шкалі симптомів
   * нуль тривоги — теж добре, тільки напрямок «нижче = гірше» там неправильний.
   *
   * Без цього прапор «варто уваги» вмикається **наоборот**: людині з нулем
   * тривоги показувалося червоне «потрібна розмова». Це не косметика — це
   * повідомлення про допомогу людині, якій вона не потрібна.
   */
  readonly severityDirection: "higher-is-worse" | "lower-is-worse";
  /**
   * Що вважати значущою зміною **з поточним одиницям виміру**.
   *
   * WHO-5 вимірює зміну у відсотках (10% — документ ВОЗ Європа), а шкали
   * симптомів — у балах. Тримати один `%` означало б щоразу перемножувати на 4
   * там, де потрібні бали. Тому одиниця явно названа, а правило одне.
   */
  readonly significantChange: SignificantChange;
}

/** Тест самооцінки: одне проходження, одна й більше шкал на виході. */
export interface AssessmentTest {
  readonly key: string;
  readonly title: string;
  /** Що міряє — одне речення, без «діагнозує депресію». */
  readonly lead: string;
  /**
   * Довідка про **сам інструмент** (скільки питань, яка шкала, який період) —
   * те, що однакове для кожного, хто його проходив. Живе в акордеоні, бо
   * людину прийшла результат, а не опис методики; дані **її власного** заміру
   * туди не належать.
   */
  readonly about: string;
  /** За який період відповідає людина («за останні два тижні»). */
  readonly periodLabel: string;
  /** Усі питання проходження, у порядку показу. Шкала питання — в `item.scale`. */
  readonly items: readonly AssessmentItem[];
  /**
   * Шкала, яку показують людині. Порядок — від найбільшого бала до найменшого,
   * але це **дані для показу**: рахунок спирається на `value`, тож перестановка
   * рядків нічого не змінює в підсумку.
   */
  readonly options: readonly ScaleOption[];
  /** Порядок блоків на екрані проходження й у картці результату. */
  readonly scales: readonly AssessmentScale[];
  /**
   * Джерела. **Масив, а не одне поле**: PHQ-9 і GAD-7 — два незалежні
   * інструменти, кожен зі своєю публікацією, тож один тест має двох
   * авторів і дві ліцензії.
   */
  readonly sources: readonly AssessmentSource[];
  /** Показується на екрані результату. Це не формальність, а частина виводу. */
  readonly disclaimer: string;
  /**
   * `true` — застереження лишається відкритим на екрані результату.
   *
   * WHO-5: `false`, довідка в акордеоні (вона не змінює дій людини).
   * Тест із симптомами: `true` — специфікація вимагає примітку не приховувати
   * (`specs/phq9-gad7/01-rules.md` §3.4), бо тут результат про симптоми.
   */
  readonly disclaimerInline?: boolean;
  /** Лінії допомоги — показуються лише разом із прапорцем безпеки. */
  readonly help?: readonly HelpLine[];
  /** Спільне для всіх шкал питання про вплив (не входить у жодну суму). */
  readonly impact?: ImpactQuestion;
}

/** Значуща зміна разом із одиницею виміру — одне правило, названий масштаб. */
export type SignificantChange =
  | { readonly kind: "percent"; readonly value: number }
  | { readonly kind: "points"; readonly value: number };

/** Лінія допомоги, яку можна набрати. Номер — дані, а не константа в коді. */
export interface HelpLine {
  readonly name: string;
  readonly number: string;
  readonly note: string;
  /** Показується без розгортання: три найважливіші. */
  readonly primary?: boolean;
}

/** Питання про вплив на повсякденне життя — окремі варіанти й окремі тексти. */
export interface ImpactQuestion {
  readonly prompt: string;
  readonly options: readonly ScaleOption[];
  /** Текст за значенням відповіді (§7.4 специфікації). */
  readonly texts: Readonly<Record<number, string>>;
}

/**
 * Результат, як він лежить у базі й приходить клієнту.
 *
 * **Один рядок — одна шкала.** Проходження з двома шкалами пише два рядки, і
 * `scaleKey` їх розрізняє: так зберігається стара схема (бал, смуга, увага) без
 * колонки з JSON, а історія й тренд рахуються по кожній шкалі окремо.
 *
 * **Це знімок на момент проходження, а не формула.** `percent` і `bandKey`
 * не перераховуються заднім числом: якщо зміниться шкала, минулий результат
 * мусить лишитися таким, яким його тоді показали людині.
 *
 * `answers` зберігається разом із балом, щоб результат можна було
 * перерахувати й пояснити — і щоб людина бачила свої відповіді, а не лише
 * число.
 */
export interface AssessmentRecord {
  readonly id: number;
  readonly testKey: string;
  /** Ключ шкали, до якої цей результат належить. */
  readonly scaleKey: string;
  readonly answers: readonly number[];
  readonly raw: number;
  readonly percent: number;
  readonly bandKey: string;
  readonly needsAttention: boolean;
  readonly createdAt: string;
}
