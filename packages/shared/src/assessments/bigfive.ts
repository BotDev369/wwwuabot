/** П'ять смуг на кожен фактор — та сама розмітка, що й у ядрі рівнів. */
function bands(notes: readonly [string, string, string, string, string]): AssessmentScale["bands"] {
  const bounds: readonly [number, number][] = [
    [4, 7],
    [8, 11],
    [12, 15],
    [16, 18],
    [19, 20],
  ];
  const labels = ["Дуже низький", "Низький", "Середній", "Високий", "Дуже високий"];
  return bounds.map(([min, max], index) => ({
    key: ["very-low", "low", "middle", "high", "very-high"][index] ?? "middle",
    min,
    max,
    label: labels[index] ?? "Середній",
    note: notes[index] ?? "",
  }));
}

