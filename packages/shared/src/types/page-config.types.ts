// Явний імпорт: файл компілюється і воркерами без React-типів, тому
// глобальний простір імен `React` тут недоступний.
import type { ReactNode } from "react";
// Знак блоку — з того самого реєстру, що й решта знаків продукту. Рядок тут
// був причиною тихої порожнечі: ім'я `buttons` не існувало в наборі, і картка
// блоку в пікері стояла взагалі без знака — компілятор про це не казав.
import type { IconName } from "../components/icon-names";
// Картка товару магазину — те, що кладе в контекст вітрина для блока
// `shop-grid` (`@wwwuabot/shared/shop`).
import type { ShopCard } from "../shop/cards";

// ── Зони сторінки ─────────────────────────────────────────────────

/** Структурні регіони сторінки. */
export type BlockZone = "sidebar" | "header" | "main" | "footer";

// ── Блок (рекурсивний) ────────────────────────────────────────────

/**
 * Один блок контенту всередині зони.
 *
 * Блоки є рекурсивними: будь-який блок може мати `children` з інших блоків,
 * що дозволяє необмежену глибину вкладеності.
 */
export interface PageBlock {
  /** Унікальний ідентифікатор блоку (UUID v4). */
  id: string;

  /**
   * Тип модуля — ключ у реєстрі блоків.
   * Наприклад: 'text', 'image', 'buttons', 'list', 'divider', 'custom'.
   */
  type: string;

  /**
   * Назва блоку (необов'язково).
   * Відображається в заголовку акордеона редактора для зручної навігації.
   * Якщо не вказано — показується тип блоку з реєстру.
   */
  name?: string;

  /** Позиція блоку в межах зони (починається з 0). */
  order: number;

  /** Конфігурація модуля (залежить від типу). */
  props: Record<string, unknown>;

  /**
   * Вкладені блоки (необов'язково).
   * Рекурсивна структура — кожен вкладений блок теж може мати children.
   */
  children?: PageBlock[];

  /**
   * Умови показу блоку (необов'язково).
   * Якщо не вказано — блок показується завжди.
   * Якщо вказано — блок показується тільки коли ВСІ умови виконуються.
   */
  conditions?: BlockConditions;

  /** Чи показувати тільки адміністраторам. */
  adminOnly?: boolean;

  /** Чи показувати тільки власнику. */
  ownerOnly?: boolean;

  /** Обовʼязковий дозвіл для перегляду блоку. */
  requiredCapability?: string;
}

// ── Умови показу блоку ────────────────────────────────────────────

/**
 * Умови показу блоку — перевіряються щодо профілю користувача.
 *
 * Всі умови поєднуються через AND (всі мають виконатися).
 * Масиви значень працюють як OR (значення користувача має бути в одному з масиву).
 */
export interface BlockConditions {
  /** Роль користувача. */
  role?: string[];

  /** Тариф користувача. */
  tariff?: string[];

  /** Статус користувача. */
  status?: string[];

  /** Мінімальна знижка (%). */
  minDiscount?: number;

  /** Дозволи (permissions). */
  permissions?: string[];

  /** Довільне поле користувача (深层 перевірка). */
  fieldMatch?: Record<string, string | number | boolean>;

  /** Альтернативний блок, якщо умови НЕ виконуються. */
  fallback?: PageBlock;
}

// ── Користувач (розширений профіль) ───────────────────────────────

/**
 * Профіль користувача для системи conditional rendering.
 */
export interface UserProfile {
  id: number;
  firstName?: string;
  lastName?: string;
  username?: string;
  role?: string;
  tariff?: string;
  status?: string;
  discount?: number;
  permissions?: string[];
  language?: string;
  [key: string]: unknown;
}

// ── Конфігурація сторінки ─────────────────────────────────────────

/**
 * Повна конфігурація сторінки.
 *
 * Зберігається в колонці `page_data` таблиці `scenarios`.
 */
export interface SidebarSettings {
  /** Позиція кнопки закриття: 'left' (зліва) або 'right' (справа) */
  closeButtonPosition?: "left" | "right";
  /** Розмір тексту для пунктів меню в сайдбарі */
  fontSize?: string;
  /** Відступ між пунктами меню в сайдбарі */
  itemSpacing?: string;
}

export interface PageConfig {
  /** Версія формату (для майбутніх міграцій). */
  version: number;

  /** Блоки по зонах. */
  zones: Record<BlockZone, PageBlock[]>;

  /** Зони, які користувач явно додав (видимі в конструкторі). */
  visibleZones?: BlockZone[];

  /** Налаштування для зони сайдбару. */
  sidebarSettings?: SidebarSettings;
}

// ── Контекст блоку ────────────────────────────────────────────────

/**
 * Контекст, що передається в кожен блок при рендері.
 */
export interface BlockContext {
  /** Канонічний slug поточної сторінки. */
  slug: string;

  /** Назва сторінки. */
  title: string | null;

  /** URL фотографії сторінки (якщо є). */
  photoUrl: string | null;

  /** Дані користувача (якщо доступні). */
  user?: UserProfile;

  /** Чи є поточний користувач власником сторінки. */
  isOwner?: boolean;

  /** Додаткові дані, що передаються зі сторінки. */
  extra?: Record<string, unknown>;

  /**
   * Картки товарів магазину — для блока `shop-grid`.
   *
   * Товарів немає в `page_data`: вони живуть у таблиці `shop_products`, тож
   * блок не має звідки їх узяти сам — їх кладе той, хто знає адресу магазину
   * (вітрина — з каталогу, своя сторінка продавця — зі свого списку).
   *
   * **Відсутність і порожнеча — різні речі.** Не передано зовсім — сітки немає
   * (магазин без товарів показує заголовок без товарів нікому). Порожній
   * масив — у магазині нічого не продають. А приклад товарів для перегляду
   * шаблону дає `preview`.
   */
  shopCards?: ShopCard[];

  /**
   * Замовити товар із сітки — **те, що вміє лише вітрина**.
   *
   * Блок товарів не має ні запитів, ні покупця: картки він бере з контексту, і
   * дію йому так само кладе той, хто знає адресу магазину. Немає її — кнопки
   * немає (у перегляді шаблону замовляти нічого: там приклад, а не товари).
   */
  onShopOrder?: (productId: number) => void;

  /**
   * Сторінку показують як **перегляд шаблону**, а не як справжню.
   *
   * Це єдина різниця, якої не видно з `page_data`: перегляд показує ту саму
   * сторінку, але під нею немає нічого — ні товарів, ні користувача. Ним
   * користується блок, чий вміст лежить у своїй таблиці (`shop-grid`): у
   * перегляді він малює приклад, бо інакше шаблон магазину виглядав би
   * кількома текстовими картками.
   */
  preview?: boolean;
  /** Налаштування для зони сайдбару. */
  sidebarSettings?: SidebarSettings;
}

// ── Визначення типу блоку ─────────────────────────────────────────

/** Категорії блоків для галереї модулів. */
export type BlockCategory =
  | "content"
  | "layout"
  | "navigation"
  | "data"
  | "commerce"
  | "forms"
  | "bot-domain"
  | "analytics"
  | "raw";

/**
 * Метадані одного типу блоку.
 */
export interface BlockDefinition {
  /** Унікальний ключ типу (відповідає PageBlock.type). */
  type: string;

  /** Людська назва для UI. */
  label: string;

  /** Короткий опис модуля. */
  description?: string;

  /** Знак блоку: ім'я з реєстру `icons.tsx` (`IconName`). */
  icon?: IconName;

  /** Категорія для групування в галереї модулів. */
  category: BlockCategory;

  /** Зони, в яких цей блок може використовуватись. */
  compatibleZones: BlockZone[];

  /** JSON Schema для валідації props блоку. */
  schema: Record<string, unknown>;

  /** Дефолтні значення props. */
  defaultProps: Record<string, unknown>;
}

// ── Block component props ──────────────────────────────────────────

/**
 * Пропси, що передаються в React-компонент блоку.
 */
export interface BlockComponentProps {
  /** Дані блоку. */
  block: PageBlock;

  /** Контекст сторінки. */
  context: BlockContext;

  /** Зона, в якій рендериться блок. */
  zone: BlockZone;

  /** Вкладені блоки (якщо є). */
  children?: ReactNode;
}
