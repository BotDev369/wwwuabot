/**
 * Вітання пари — тексти, якими відкривається розмова, коли людина прийшла за
 * запрошенням.
 *
 * **Це тексти платформи, і автор у них — вона ж.** Обидві позначки лягають у
 * спільну стрічку, яку читають **обоє**, тож ім'я в них — публічне
 * (`peerPublicLabel`), а не з чийогось довідника: ім'я, яке людині дав хтось
 * інший, не можна показати третій особі (AGENTS.md §2).
 *
 * **Чому тут, а не в `api-dev`.** Правило «що саме написано у вітанні» одне на
 * продукт, і воно мусить перевірятись без бази: сервер лише викликає його й
 * кладе рядки в базу. Друга копія тексту в другої оболонки розійшлася б із
 * першою — саме тому тексти живуть у спільному модулі, а не біля контролера.
 *
 * @module @wwwuabot/shared/messages
 */

/**
 * Дві позначки, якими відкривається розмова: **запрошення** й **зв'язок**.
 *
 * Обидві навмисно короткі: це службові рядки, а не привітання від людини, і
 * місце для першого справжнього повідомлення мусить лишатись вільним.
 */
export interface ConversationGreeting {
  /** Кого запросили — і хто саме запросив. */
  invited: string;
  /** Зв'язок встановлено: те, заради чого людина прийшла за лінком. */
  connected: string;
}

/**
 * Тексти вітання за **публічним** іменем того, хто запросив.
 *
 * Друга позначка без імені навмисно: вона про факт («ви на зв'язку»), і
 * повторене в ній ім'я читалось би як два різні звернення поспіль.
 */
export function conversationGreeting(inviterName: string): ConversationGreeting {
  return {
    invited: `${inviterName} запрошує до конфіденційної бесіди`,
    connected: "Контакт встановлено — тепер ви на зв'язку одне з одним",
  };
}

/** Обидві позначки по порядку — те, що кладеться в стрічку одним відкриттям. */
export function greetingNotes(inviterName: string): string[] {
  const greeting = conversationGreeting(inviterName);
  return [greeting.invited, greeting.connected];
}
