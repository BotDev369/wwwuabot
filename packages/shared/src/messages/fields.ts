/**
 * Правила тіла повідомлення й пари розмови — чисті функції.
 *
 * **Чому спільно, а не на сервері.** Ті самі правила потрібні двом місцям:
 * сервер ними пише, клієнт ними ж показує («надіслати» гасне на порожньому
 * полі, лічильник довжини рахує те саме число). Друга копія розійшлася б із
 * першою на першій же правці — і людина бачила б кнопку, яка нічого не робить.
 *
 * @module @wwwuabot/shared/messages
 */

/** Стеля тіла одного повідомлення. */
export const MAX_MESSAGE_BODY = 2000;

/** Скільки знаків останнього повідомлення показує рядок списку розмов. */
export const MESSAGE_PREVIEW_LENGTH = 80;

/**
 * Тіло повідомлення, як воно ляже в базу: без пробілів по краях і не довше за
 * `MAX_MESSAGE_BODY`.
 *
 * Обрізаємо **на записі**, а не на показі: інакше обрізаний текст жив би в базі
 * й повертався б іншим у кожному клієнті (зокрема в тому, який про стелю не
 * знає). Краї притискаємо, бо повідомлення з самих пробілів — це порожній
 * рядок, і показувати його як повідомлення нема чого.
 */
export function sanitizeMessageBody(raw: unknown): string {
  if (typeof raw !== "string") return "";
  return raw.trim().slice(0, MAX_MESSAGE_BODY);
}

/** Чи з цього тіла вийде повідомлення. */
export function isSendableBody(raw: unknown): boolean {
  return sanitizeMessageBody(raw).length > 0;
}

/**
 * Один рядок для списку розмов: переноси згортаємо в пробіли, довге — ріжемо.
 *
 * Саме один рядок, бо рядок списку має **фіксовану** висоту: багаторядковий
 * останок робив би розмови різної висоти, і список читався б як стрічка.
 */
export function messagePreview(body: string, max = MESSAGE_PREVIEW_LENGTH): string {
  const line = body.replace(/\s+/gu, " ").trim();
  return line.length > max ? `${line.slice(0, max - 1).trimEnd()}…` : line;
}

/**
 * Пара людей у порядку зростання id — **єдине місце**, де цей порядок заданий.
 *
 * Розмова одна на двох, а не по одній на кожного: якби рядок заводився від
 * того, хто написав першим, та сама переписка лежала б у двох рядках, і кожен
 * бачив би половину. Тому порядок не «дрібниця схеми», а правило, від якого
 * залежить, чи побачать люди одне одного.
 */
export function conversationPair(a: number, b: number): [number, number] {
  return a <= b ? [a, b] : [b, a];
}

/** Співрозмовник у парі: той із двох, хто не я. */
export function peerOf(peerA: number, peerB: number, me: number): number {
  return peerA === me ? peerB : peerA;
}
