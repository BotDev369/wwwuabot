/**
 * Сигнал «непрочитане могло змінитись» — **один** спосіб сказати бейджу, що
 * його число застаріло.
 *
 * **Навіщо.** Число непрочитаних рахує сервер (єдине джерело правди), а бейдж
 * опитує його раз на крок таймера. Через це він **залипає**: людина відкриває
 * розмову, сервер позначає її прочитаною, а смуга показує старе число аж до
 * наступного опитування — тобто розмову вже прочитано, а лічильник і далі
 * показує непрочитане.
 *
 * Тому той, хто **змінив** стан переписки (прочитав, стер, прибрав), каже про
 * це одним викликом, а бейдж перечитує число **зразу**, не чекаючи кроку.
 *
 * **Числа тут немає навмисно.** Підписка не «зменшує» лічильник собі — вона
 * лише просить перерахувати його в сервера. Друге сховище того самого факту
 * розійшлося б із сервером на першій же помилці запису: «прочитано» ставить
 * саме сервер, і саме він знає, скільком повідомленням це сталося.
 *
 * @module @wwwuabot/shared/messages
 */

/** Слухач сигналу: нічого не отримує — йому кажуть «перечитай», а не «ось число». */
type UnreadListener = () => void;

/**
 * Слухачі сигналу.
 *
 * Стан на рівні модуля, а не в компоненті: бейдж і екран переписки — різні
 * дерева (смуга стоїть **поза** сторінкою), і передати одному з них функцію
 * іншого нічим: між ними немає спільного предка з цим станом.
 */
const listeners = new Set<UnreadListener>();

/**
 * Сказати, що число непрочитаних могло змінитись.
 *
 * Викликають його **після** відповіді сервера, а не на сам дотик: бейдж за
 * сигналом перечитує число, і покликаний раніше він приніс би те саме старе.
 */
export function notifyUnreadChanged(): void {
  // Копія списку — бо слухач має право відписатись у самому виклику (це
  // робить ефект, який знімається), і зміна `Set` під час обходу пропустила б
  // наступного слухача.
  for (const listener of [...listeners]) listener();
}

/** Слухати сигнал; повертає відписку. */
export function onUnreadChanged(listener: UnreadListener): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}
