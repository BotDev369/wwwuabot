/**
 * Адреса розмови — одна на бота й на платформу.
 *
 * **Чому спільно.** Розмову відкривають із двох боків: бот дає кнопку «Відкрити
 * чат» (людина прийшла за запрошенням), а платформа цю адресу читає, щоб
 * відкрити саме ту розмову. Два літерали `/messages?peer=` у двох воркерах
 * розійшлися б тихо — кнопка вела б у порожній список, і ніщо б про це не
 * сказало.
 *
 * **Адреса є лише входом.** Стан екрана вона не тримає: «відкрита розмова» —
 * це те, що людина робить зараз, а не те, чим розмова є. Тому параметр лише
 * читається при відкритті й далі живе у стані екрана.
 *
 * **Кому можна відкрити — вирішує сервер.** Номер у параметрі нікого не
 * авторизує: `GET /api/messages/thread` спершу перевіряє зв'язок через контакти
 * (`api-dev/src/services/messages/links.ts`), тож чужий номер дістає ту саму
 * відмову, що й неіснуючий.
 *
 * @module @wwwuabot/shared/messages
 */

/** Маршрут екрана повідомлень у платформі. */
export const MESSAGES_PATH = "/messages";

/** Параметр адреси: з ким саме відкрити розмову. */
export const MESSAGES_PEER_PARAM = "peer";

/**
 * Шлях до розмови з конкретною людиною.
 *
 * `peerId` тут — **Telegram-id** (той самий, що в `users.user_id`), бо саме ним
 * адресується співрозмовник у кожному запиті переписки.
 */
export function messagesPeerPath(peerId: number): string {
  return `${MESSAGES_PATH}?${MESSAGES_PEER_PARAM}=${peerId}`;
}

/**
 * Номер співрозмовника з адреси; `null` — адреса його не називає.
 *
 * Додатне ціле — не формальність: Telegram-id завжди додатний, тож нуль,
 * від'ємне й «12abc» — це не «невідомий співрозмовник», а відсутність адреси.
 */
export function readMessagesPeer(value: string | null | undefined): number | null {
  if (typeof value !== "string" || value.trim() === "") return null;
  const id = Number(value);
  return Number.isInteger(id) && id > 0 ? id : null;
}
