/**
 * Текст нотатки — правила, спільні для композера й сервера.
 *
 * Довжина обмежена не «щоб щось обмежити»: `notes.text` — це `TEXT` у D1, і
 * без стелі один вставлений документ зробив би нотатку, яку неможливо ні
 * показати, ні прогнати через API. Стеля одна на обидві поверхні: браузер
 * показує її полем (`maxlength`), а api-dev — не дає записати більше.
 *
 * @module @wwwuabot/shared/notes
 */

/** Максимальна довжина нотатки (символів). */
export const MAX_NOTE_LENGTH = 20_000;

/**
 * Текст із того, що прийшло ззовні: обрізає краї й стелю.
 *
 * Обрізаємо **краї**, а не все всередині: порожні рядки в нотатці — це те, як
 * люди нею користуються, а от пробіл на початку й у кінці завжди випадковий.
 */
export function sanitizeNoteText(input: unknown): string {
  if (typeof input !== "string") return "";
  return input.trim().slice(0, MAX_NOTE_LENGTH);
}
