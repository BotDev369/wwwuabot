/**
 * Сценарій, який веде людина, — рядок таблиці `scenarios`.
 *
 * **Чому саме `scenarios`.** Там уже живе сторінка вебу (`page_data`) разом із
 * її поданням у боті, і адреса там одна — `slug`. Друга таблиця під той самий
 * контент дала б два сховища одного `PageConfig` і друге правило «яка сторінка
 * для цього URL» (`AGENTS.md` §7). Тому сценарій — це **той самий рядок**, лише
 * з власником (`owner_id`), прапорцем видимості (`is_public`) і ключем шаблону
 * (`template_key`).
 *
 * **Це те, що читають, а не те, що надсилають.** Сторінку не створюють і не
 * правлять із інтерфейсу — її заводить платформа кодом і міграціями. Тому тут
 * немає ні чернетки, ні відповіді запису: дія, якої не існує, не має й типу.
 *
 * **Значень тут немає.** Текст живе в `page_data` — у блоках, які будує
 * `buildPageConfig()`. Поля їдуть у клієнт **виведеними** з тієї ж конфігурації
 * (`readPageValues`): тримати їх поруч із `page_data` означало б мати два місця
 * правди про один текст.
 *
 * @module @wwwuabot/shared/pages
 */

import type { PageFieldValues, PageTemplateKey } from "./templates";

/** Роль людини в сценарії: власник або той, кого він додав адміном. */
export type PageRole = "owner" | "admin";

/**
 * Хто веде сценарій — як це показує картка «Доступ».
 *
 * `name` — ім'я на платформі (`#ім'я`), а немає — `@хендл` чи ім'я з Telegram:
 * рядок одного перекладу імені лежить у `peerLabel` (`@wwwuabot/shared/messages`),
 * і другий переклад тут був би другою правдою про те, як звуть людину.
 */
export interface PageStaff {
  id: number;
  name: string | null;
  role: PageRole;
}

/** Сценарій, який веде людина, як він їде в клієнт. */
export interface ManagedScenario {
  id: number;
  /** Адреса сторінки: за нею її відкривають (`/slug`). */
  slug: string;
  /** Назва — вона ж підпис у списку, заголовок сторінки й назва в боті. */
  title: string;
  template: PageTemplateKey;
  /** Тексти полів, виведені з `page_data` (див. `readPageValues`). */
  values: PageFieldValues;
  /** `true` — сторінку видно іншим; `false` — тільки тому, хто її веде. */
  isPublic: boolean;
  /**
   * Хто веде сценарій: власник першим, далі адміни.
   *
   * Список, а не саме лише «моя роль»: картка «Доступ» показує його цілком, а
   * склад адмінів із нього ж і виводиться (`pageAdminsOf`) — друга копія тих
   * самих id розійшлася б із першою.
   */
  staff: PageStaff[];
  /** Моя роль тут: чужого сценарію в цьому списку не буває. */
  role: PageRole;
  updatedAt: string;
}

/** Відповідь `GET /api/user/pages`: сценарії, які веде людина. */
export interface PageListResponse {
  ok: boolean;
  pages: ManagedScenario[];
}
