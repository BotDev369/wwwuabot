/**
 * Українські форми множини — в одному місці на весь продукт.
 *
 * **Дві копії — дві правди, і одна з них уже помилялася.** Слово «спроба» в
 * іграх і «товар» у магазині рахувалися двома різними функціями, причому
 * магазинна для 111–114 давала «111 товар» замість «111 товарів»: її гілка
 * «11–20» дивилася на повне число, а не на його останні дві цифри. Тому
 * правило одне, і воно тут.
 *
 * **Числа 11–14 — окрема гілка.** Вони закінчуються на 1–4, але множини не
 * беруть: «11 спроб», а не «11 спроба». Дивитися треба на останні дві
 * цифри (`n % 100`), а не на останню (`n % 10`) — саме в цьому була
 * помилка копії з магазину.
 *
 * @module @wwwuabot/shared/utils/plural
 */

/** Три форми українського іменника: для 1, для 2–4 і для решти. */
export type PluralForms = readonly [one: string, few: string, many: string];

/**
 * Форма слова для числа.
 *
 * `@param count` — саме число, а не модуль: «11» і «111» обидва закінчуються
 * на 1, але множину беруть лише перші.
 */
export function plural(count: number, forms: PluralForms): string {
  const hundred = Math.abs(count) % 100;
  if (hundred >= 11 && hundred <= 14) return forms[2];
  const tail = hundred % 10;
  if (tail === 1) return forms[0];
  if (tail >= 2 && tail <= 4) return forms[1];
  return forms[2];
}
