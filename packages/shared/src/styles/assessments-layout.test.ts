/**
 * Сторож висоти екрана проходження: **контент має вміщуватись без гортання**.
 *
 * Чому це тест, а не коментар. Власник 29.09.2026 показав скриншот і сказав:
 * «все вміщалось на одному екрані, а то доводиться гортати». Причина була не в
 * довжині текстів, а в одному рядку: `.wb-run` мав `min-height: 100dvh` і лежав
 * усередині `.wb-app`, яка вже має `height: 100dvh` і `overflow: hidden`.
 * Тобто вміст був висотою в цілий екран **плюс** шапка над ним — шість
 * варіантів, питання й кнопка не могли вміститись ні на одному питанні.
 *
 * Правило: розмір екрана вмісту береться **від контейнера сторінки** (100%),
 * а не від екрана пристрою (`dvh`/`vh`). Інакше будь-яка рамка над вмістом —
 * шапка, футер — додає другий екран прокрутки.
 *
 * Розбору CSS у тестовому середовищі немає (environment: node, без DOM), тож
 * читається як текст — так само, як у `buttons.test.ts` і `fields.test.ts`.
 *
 * @module packages/shared/src/styles/assessments-layout.test
 */

import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const css = readFileSync(new URL("./assessments.css", import.meta.url), "utf8");

/** Правило для селектора — разом із вкладеними блоками, як їх бачить CSSOM. */
function rule(selector: string): string {
  const start = css.indexOf(`\n${selector} {`);
  expect(start, `правило ${selector} має існувати`).toBeGreaterThan(-1);
  const open = css.indexOf("{", start);
  const close = css.indexOf("\n}", open);
  return css.slice(open, close);
}

describe("екран проходження", () => {
  it("не задає висоту від екрана пристрою", () => {
    // Регресія: `min-height: 100dvh` усередині вже обмеженого контейнера —
    // гарантований зайвий екран прокрутки на кожному з п'яти питань.
    expect(rule(".wb-run")).not.toMatch(/\d+d?vh/);
  });

  it("кнопка кроку притискається до низу колонки, а не тоне в списку", () => {
    expect(rule(".wb-run > .wb-btn")).toContain("margin-top: auto");
  });

  it("«далі» до вибору не виглядає як кнопка, на яку можна натиснути", () => {
    const waiting = rule(".wb-btn-waiting");
    expect(waiting).toContain("background: transparent");
    expect(waiting).toContain("var(--text-muted)");
  });
});

/**
 * Розмір заголовків секцій на картці результату.
 *
 * Власник 29.09.2026 показав скриншот, де «На що варто звернути увагу»
 * займав два рядки й виглядав більшим за текст під ним. Причина була не в
 * розміті: `android.css` піднімає **будь-який** `h2` до
 * 28px/22px через `!important`, а ці заголовки — `h2`. Тобто правило секції
 * (`0.9375rem`) просто не діяло.
 */
describe("заголовки секцій результату", () => {
  it("не піднімаються бренд-темою до розміру заголовка екрана", () => {
    for (const selector of [".wb-section-title", ".wb-alerts-title"]) {
      expect(rule(selector), selector).toContain("font-size: 0.9375rem !important");
    }
  });
});

/**
 * Блок «Ти не один» — розподіл по смугах.
 *
 * Власник попросив показувати свій результат поруч із загальним станом усіх,
 * хто проходив. Дві речі тут не stylistic, а правила:
 *
 *  1. **Одна нейтральна лінійка на всі смуги.** Кольорова шкала від доброго
 *     до поганого читалася б як оцінка стану, а це те саме, від чого блок
 *     відсторонює: людина прийшла за масштабом, а не за діагнозом. Колір
 *     лишається тільки на рядку людини.
 *  2. **Лінійка має куди вміститись.** Без `minmax(0, 1fr)` довге «Значно
 *     виражені симптоми» витіснило б її в нуль, і смуга зникла б саме там,
 *     де вона найважливіша.
 */
describe("розподіл між людьми", () => {
  it("смуги всі одного кольору, а коліром виділено лише рядок людини", () => {
    const plain = rule(".wb-peers-fill");
    const mine = rule(".wb-peers-row--mine .wb-peers-fill");
    expect(plain).toContain("var(--border)");
    // Акцент на своєму рядку — єдина кольорова пляма в блоці.
    expect(mine).toContain("var(--accent)");
    expect(plain).not.toBe(mine);
  });

  it("лінійка не стискається підписом смуги", () => {
    expect(rule(".wb-peers-row")).toContain("minmax(0, 1fr)");
    expect(rule(".wb-peers-name")).toContain("min-width: 0");
  });

  it("лічильник людей не переноситься на два рядки", () => {
    // «12 людей · 34%» має бути одним числом, а не «12 людей» і «34%»
    // на двох рядках — те саме, що вже було з балом у шапці картки.
    expect(rule(".wb-peers-count")).toContain("white-space: nowrap");
  });
});

/**
 * Бал у шапці картки списку не розривається.
 *
 * Власник 29.09.2026 показав скриншот: «Індекс благополуччя» займає два
 * рядки, і «з 25» падало на наступний — число виглядало розбитим на два
 * різні значення. Причина: назва стискала бал у вузьку колонку, а
 * `white-space` ніде не було задано.
 */
describe("бал у шапці картки", () => {
  it("не переноситься і не стискається назвою", () => {
    const score = rule(".wb-test-score");
    expect(score).toContain("white-space: nowrap");
    expect(score).toContain("flex: 0 0 auto");
  });

  it("менший за бал на картці результату — там він головний", () => {
    // Розмір у rem, а не в px: разом із `--text-*` він лишається в одній
    // мові з рештою розмірів і переживає зміну теми.
    const list = rule(".wb-test-score").match(/font-size: ([\d.]+)rem/);
    const card = rule(".wb-score-value").match(/font-size: ([\d.]+)rem/);
    expect(list).not.toBeNull();
    expect(card).not.toBeNull();
    expect(Number(list?.[1])).toBeLessThan(Number(card?.[1]));
  });

  it("немає результату — місце лишається, а не зникає", () => {
    // Картка без результату мусить займати стільки ж місця в рядку, інакше
    // пустий кут читається як «бал не вмістився», а не «тест не пройдено».
    expect(rule(".wb-test-score--none")).toContain("var(--text-muted)");
  });
});
