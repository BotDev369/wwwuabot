/**
 * ═══════════════════════════════════════════════════════════════════════════
 * SCHEME REGISTRY — одна схема-стан × дві світлоти
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * Застосовується лише CSS-атрибутом — без жодного JS-стилю в рантаймі:
 *   <html data-theme="light|dark">
 *
 * **Стиль продукту один і вибору не має.** Ним керує CSS (`tokens.css` —
 * світла схема й мірки, `themes.css` — темна): ні атрибута, ні константи
 * стилю в коді немає: шару стилів, який можна було вибрати чи перемкнути,
 * більше не існує — поки він існував, будь-яка деталь могла мати два значення.
 */

/** Світлота — світла чи темна. «Системної» немає: її виводить вибір кольорів. */
export type Scheme = "light" | "dark";

export type Theme = Scheme;
