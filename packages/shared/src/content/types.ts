/**
 * Контент сторінки — модель, спільна для всіх сховищ.
 *
 * **Навіщо.** Один і той самий контент — `PageConfig` у колонці `page_data` —
 * лежав у чотирьох сховищах. Три з них (`scenarios-admin`, `sites`,
 * `site_pages`) видалено 13.09.2026 разом із таблицями: `scenarios-admin` не
 * читав ніхто поза адмінкою, а `sites` + `site_pages` були другою реалізацією
 * того самого для вебу. Того ж дня з реєстру прибрано й `pages` — таблицю, яку
 * додали як «цільову»: на дев-базі вона не існувала, нічого не читала й нічого
 * не зберігала, тобто була ще одним сховищем-двійником.
 * **Місце одне — `scenarios`:** рядок таблиці і є сторінкою (тут `page_data`)
 * разом із її поданням у боті.
 * Тип контенту один, а читання його було розкидане по кожному місцю окремо:
 * контролер сценаріїв парсив JSON сам, `toSitePage` — сам, платформа — ще раз
 * через `JSON.stringify`/`parsePageConfig`. Цей модуль дає **одну форму**, до
 * якої зводиться рядок, і **одне правило** «яка сторінка для цього URL».
 *
 * Модель **не** знає про воркери й не робить запитів: це чисті типи та
 * функції, тож їх використовують і `api-dev`, і обидві оболонки, і бот.
 *
 * **Одна адреса, не дві.** У `ContentPage` є рівно одне поле адреси — `slug`.
 * `web_slug` і `codeword` (дві колонки, у яких лежав той самий рядок) зведені
 * до нього адаптером; подання адреси для бота й для вебу будує `resolve.ts`.
 *
 * @module @wwwuabot/shared/content
 */

import type { PageConfig } from "../types/page-config.types";

/**
 * Сторінка контенту в нормалізованому вигляді.
 *
 * Одна форма для трьох таблиць. Поля, яких у сховищі немає, заповнюються
 * безпечним значенням (`null` / `0`), а не вигаданим: краще `null`, ніж
 * правдоподібне, але хибне.
 */
export interface ContentPage {
  /**
   * Стабільний ідентифікатор запису.
   *
   * У сценаріїв окремого `id` немає — там записом слугує адреса. Поле є, бо
   * за ним сторінку шукають навігація й майбутні зв'язки між сторінками.
   */
  id: string;

  /**
   * Адреса сторінки — **єдина** сутність ідентичності: і шлях вебу, і основа
   * діплінка бота. Порожній рядок — головна сторінка.
   *
   * Подання: `toWebPath()` дає `/mydate/1980-03-03/today`, `toBotPayload()` —
   * `mydate_1980-03-03_today`. Див. `resolve.ts`.
   */
  slug: string;

  /** Заголовок сторінки. `null` — не заданий. */
  title: string | null;

  /**
   * Фото сторінки. `null` — не задане.
   *
   * Це метадані самої сторінки (у сценаріїв — `photo_url`), і саме їх
   * `PageRenderer` кладе в `BlockContext.photoUrl`.
   */
  photoUrl: string | null;

  /**
   * Контент для `PageRenderer`.
   *
   * `null` означає «сторінка існує, але контенту в ній немає» — це стан
   * новоствореного сценарію, і він відрізняється від порожньої конфігурації.
   */
  content: PageConfig | null;

  /**
   * Чи доступна сторінка назовні **за правилом свого сховища**:
   * `is_active = 1` для сценаріїв.
   *
   * Поле не вирішує, що показувати: фільтрує сховище (SQL або список у
   * пам'яті), бо в редакторі чернетка мусить бути видимою.
   */
  published: boolean;

  /** Порядок у межах групи. `0` для сценаріїв — там порядку немає. */
  order: number;
}

/**
 * Мінімальний рядок сценарію, потрібний для нормалізації.
 *
 * Навмисно не `ScenarioRow` із `bot-dev`: у кожного воркера свій повний тип,
 * а спільна модель мусить залежати лише від тих колонок, які справді читає.
 *
 * **Імена колонок тут — ті, що є в таблиці.** `codeword` і `web_slug` — дві
 * колонки, у яких лежить та сама адреса (історична особливість `scenarios`).
 * Адаптер (`adapters.ts`) зводить їх до одного `ContentPage.slug`. Таблиці, у
 * яку цей рядок мав би «переїхати», немає: `scenarios` і є сховищем.
 */
export interface ScenarioContentRow {
  codeword: string;
  title?: string | null;
  photo_url?: string | null;
  page_data?: string | null;
  web_slug?: string | null;
  is_active?: number | string | null;
}
