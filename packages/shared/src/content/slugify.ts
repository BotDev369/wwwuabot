/**
 * Текст → сегмент адреси: переклад кирилиці латиницею і чистка.
 *
 * **Мова адреси — латиниця, і це не смак.** Сегмент мусить без втрат стати і
 * веб-шляхом, і Telegram-payload (`?start=`), а Telegram приймає лише
 * `A-Za-z0-9_-`. Українська назва без перекладу дала б порожній сегмент, тож
 * кирилиця не **відкидається**, а **перекладається** — і таблиця перекладу
 * живе тут, бо адрес у продукті вже дві (сторінка й товар магазину), і друга
 * копія цієї таблиці розійшлася б із першою тихо.
 *
 * **`_` усередині сегмента заборонений** (`isValidSlug`): він розділювач у
 * Telegram-payload. Тому будь-який розділювач стає дефісом, а не лишається
 * собою.
 *
 * **Стеля — довжина адреси, а не красивість.** Обрізати сегмент мусить той, хто
 * його складає: у сторінки своя стеля (її payload їде в бота цілком), у товару —
 * своя (він їде **хвостом** після адреси магазину). Тому `max` — аргумент, а не
 * константа цього файлу.
 *
 * @module @wwwuabot/shared/content/slugify
 */

/** Переклад кирилиці латиницею — для адреси з назви. */
const TRANSLIT: Record<string, string> = {
  а: "a",
  б: "b",
  в: "v",
  г: "h",
  ґ: "g",
  д: "d",
  е: "e",
  є: "ie",
  ж: "zh",
  з: "z",
  и: "y",
  і: "i",
  ї: "i",
  й: "i",
  к: "k",
  л: "l",
  м: "m",
  н: "n",
  о: "o",
  п: "p",
  р: "r",
  с: "s",
  т: "t",
  у: "u",
  ф: "f",
  х: "kh",
  ц: "ts",
  ч: "ch",
  ш: "sh",
  щ: "shch",
  ь: "",
  ю: "iu",
  я: "ia",
  ы: "y",
  э: "e",
  ё: "e",
  ъ: "",
};

/**
 * Сирий текст → сегмент адреси, не довший за `max`.
 *
 * Пробіл, `_` і будь-який інший розділювач стають дефісом, усе зайве
 * відкидається. Стеля ріжеться **до** останньої чистки: інакше обрізаний
 * сегмент міг би закінчитись дефісом — `-` у кінці адреси виглядає як
 * незакінчене слово, і саме так його читають.
 */
export function transliterateSlug(raw: unknown, max: number): string {
  if (typeof raw !== "string") return "";

  const mapped = [...raw.toLowerCase()]
    .map((char) => (char in TRANSLIT ? TRANSLIT[char] : char))
    .join("");

  return (
    mapped
      // `\p{L}` і `\p{N}` — щоб відкинути не-латиницю, якої немає в таблиці
      // (грек, ієрогліфи): адреса мусить лишатись ASCII.
      .replace(/[^\p{L}\p{N}]+/gu, "-")
      .replace(/[^a-z0-9-]+/g, "-")
      .replace(/-{2,}/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, max)
      .replace(/-+$/g, "")
  );
}
