import type { ReactNode } from "react";
import type { IconName } from "../icons";
import { ico } from "./badges";

/**
 * Картка розділу профілю: заголовок зі знаком і вміст під ним.
 *
 * Це **кирпичик**, а не оформлення одного екрана: та сама картка стоїть у
 * картці адмінки (ім'я, дані системи, Telegram, сирі поля) і в розділах сторінки
 * акаунта. Виписана в розмітці, вона розійшлася б першою: розмір заголовка,
 * відступ і знак — три речі, які кожен наступний екран зробив би «майже так»
 * (AGENTS.md §3).
 *
 * **Вміст від картки відділений навмисно.** Розділ може скласти в **одній**
 * картці дві речі, яких у житті не розділити — ім'я на платформі й дані акаунта
 * (те й те «про мене»). Тому рамку з заголовком дає той, хто складає розділ, а
 * не той, хто малює поля: інакше вкладена картка в картці казала б, що це різні
 * речі.
 */
export function ProfileCard({
  title,
  icon,
  children,
}: {
  title: string;
  icon: IconName;
  children: ReactNode;
}) {
  return (
    <div className="wb-profile">
      <h3 className="wb-profile-title">
        {ico(icon)} {title}
      </h3>
      {children}
    </div>
  );
}
