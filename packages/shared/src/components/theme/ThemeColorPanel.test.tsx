/**
 * Сторож панелі вигляду: **що в ній є і що в ній бути не має**.
 *
 * Тут ламається дві речі одразу, і обидві мовчки. Перша — склад: якщо зникне
 * другий рядок пункту («що обрано»), меню перетвориться на два заголовки без
 * змісту, і людина не бачитиме свого вибору, не розкриваючи пункт. Друга —
 * рядок дій: кнопка без пари («Застосувати» без «Відмінити») означає б, що
 * скасувати вибір нічем.
 *
 * **Вибору стилю тут немає й не має бути.** Стиль продукту — константа
 * (`styles/registry`), тому кнопка «Material» у панелі була б вибором, який
 * нічого не змінює.
 *
 * **Рядка дій у панелі немає.** «Застосувати» з «Відмінити» тримали чернетку
 * й відкочували її на виході, тож закрита панель губила вибір — тема не
 * застосовувалася. Тепер натискання палітри чи шрифту і є застосуванням, і ці
 * кнопки мусять бути відсутні.
 *
 * **Панель — вибір, а не редактор.** Рядків «фон / основний / акцент» у ній
 * бути не має: вони живуть у редакторі теми, а тут лише джерела (палітри чи
 * вкладки бібліотек). Те саме й зі шрифтом: окремої секції «Шрифт теми» більше
 * немає — шрифт частина схеми, тож міняється там же, де й кольори. Рядок «Застосовано на цьому пристрої» теж зник: він
 * повторював незмінне, а стан тепер показує сама кнопка «Застосувати».
 *
 * Рендер — справжній (`renderToStaticMarkup`): правило панелі цікаве тим, що
 * його видно в розмітці — `aria-expanded`, підписи кнопок і `disabled`.
 *
 * @module packages/shared/src/components/theme/ThemeColorPanel.test
 */

import { describe, expect, it } from "vitest";
import { renderToStaticMarkup } from "react-dom/server";
import { ThemeColorPanel } from "./ThemeColorPanel";

function render(): string {
  return renderToStaticMarkup(<ThemeColorPanel />);
}

describe("панель вигляду", () => {
  it("⛔ панель — це тільки вибір: ні секцій, ні дубля обраної теми", () => {
    const html = render();

    // Пункт один, тож акордеон лише приховував би його; другий рядок «обрано:
    // …» дублював би виділення картки. Обидва — дві правди про одне.
    expect(html).not.toContain("wb-theme-section");
    expect(html).not.toContain("Кольори теми");
    expect(html).not.toContain("Шрифт теми");
    // Списку шрифтів у панелі немає — він у редакторі теми. Підпис «Як у
    // стилі» на картці лишається: він каже шрифт схеми, а не відкриває вибір.
    expect(html).not.toContain("wb-font-picker");
    // Стиль продукту — константа: кнопка, що не змінює нічого, тут шкодить.
    expect(html).not.toContain("Material");
    expect(html).not.toContain("Apple");
  });

  it("⛔ рядка дій немає: вибір застосовується натисканням", () => {
    const html = render();

    // Кнопки діяли на чернетку, яка відкочувалася на виході: панель закривали —
    // вибір зникав. Тепер застосування і є натискання, тож кнопок немає.
    expect(html).not.toContain("Застосувати");
    expect(html).not.toContain("Відмінити");
    expect(html).not.toContain("wb-theme-actions");
    expect(html).not.toContain("Скинути");
    expect(html).not.toContain("Зберегти");
  });

  it("⛔ точне налаштування кольорів — у редакторі, а не в панелі", () => {
    const html = render();

    // Панель відкриває джерела (туди — палітри замість вкладок); рядки слотів
    // належать «Налаштувати власну», інакше одне колір міняється у двох місцях.
    // Рядки слотів (`ColorSlotRow`) живуть у редакторі теми: у панелі їх немає,
    // тож немає й класу рядка. Підписи палітрів лишаються — це інші слова.
    expect(html).not.toContain("wb-theme-row");
    expect(html).not.toContain("wb-theme-row-swatch");
  });

  it("⛔ стану «Застосовано» тут немає — застосування і так очевидне", () => {
    const html = render();

    // Рядок повторював незмінне, а після відмови від «Застосувати» він просто
    // зник би разом із чернеткою.
    expect(html).not.toContain("Застосовано");
    expect(html).not.toContain("wb-theme-status");
  });
});
