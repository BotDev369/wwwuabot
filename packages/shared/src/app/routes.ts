/**
 * Адреси екранів платформи, які **не** є рядком контенту — і якими користується
 * не лише платформа.
 *
 * **Чому це в `shared`.** Ці адреси читає платформа (футер і список сервісів),
 * а сценарій бота тепер ставить посилання кнопкою у власному HTML — спільного
 * рядка емодзі більше немає, тож літерали тут не дублюються.
 *
 * **Тільки входи, а не всі адреси платформи.** Решту (`/ads`, `/games`,
 * `/pages`, `/notes`, `/contacts`) читає лише вона, і дублювати їх тут без
 * потреби — це другий список, який доведеться тримати разом із першим.
 *
 * **Футер і рядок кнопок бота — один склад.** П'ять входів: акаунт, обране,
 * трекери, розвиток, Сервіси. Обидва місця читають ці літерали, а порядок
 * задає кожен свій список — різниця в порядку тут лише тому, що бот ставить
 * «Сервіси» останнім.
 *
 * @module @wwwuabot/shared/app/routes
 */

/** Акаунт — дані людини на платформі й у Telegram: фото, імена, публічність. */
export const ACCOUNT_PATH = "/account";

/** Обране — збережені сторінки й товари. */
export const FAVORITES_PATH = "/favorites";

/**
 * Трекери — власні щоденні записи людини: третій вхід футера й кнопка бота.
 *
 * Адреса в `shared`, бо її читають двоє; деталь трекера — `/trackers/:id`.
 */
export const TRACKERS_PATH = "/trackers";

/**
 * Розвиток — самооцінка й аналіз власних дат: четвертий вхід футера й кнопка
 * бота. Проходження тесту — `/assessments/:key` (там само в оболонці).
 */
export const ASSESSMENTS_PATH = "/assessments";

/** Сервіси — список екранів платформи: п'ятий пункт футера і кнопка бота. */
export const SERVICES_PATH = "/services";
