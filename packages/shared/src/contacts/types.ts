/**
 * Типи контакту — одна форма на сервер і на обидві оболонки.
 *
 * **Контакт — це запис, а не лінк.** Раніше рядок був «лінком запрошення», і
 * все, що про людину знали, — підпис і факт приєднання. Тепер запис заводять
 * руками (ім'я, хештеги, примітки), а лінк — одне з його полів: контакт може
 * існувати **без** лінка, і це нормальний стан, а не «незавершене створення».
 *
 * Тому полів два роди, і плутати їх не можна:
 *
 * - **власні** (`name`, `tags`, `notes`) — їх пише людина в картці, і вони є
 *   завжди, навіть коли лінка немає;
 * - **наслідкові** (`username`, `joinedUserId`, `joinedBotAt`,
 *   `joinedPlatformAt`, `code`, `invitedCount`) — їх записує система, і
 *   **жодного з них власник не вписує руками**.
 *
 * `username` серед наслідкових, бо власник його **не знає**: хендл приходить
 * разом із людиною, коли та переходить за особистим лінком (`bot-dev` пише його
 * в момент закріплення). Поле вводу обіцяло б знання, якого немає, і дало б
 * змогу вписати чуже ім'я — а тоді картка й бот показували б різних людей.
 *
 * **Два входи — два факти.** Людина може зайти в бота за лінком і не відкрити
 * платформу: тоді вона приєдналась **частково**, і це не те саме, що повне
 * приєднання. Тому дат дві, і кожну ставить той, хто бачив подію:
 *
 * | Колонка | Хто пише | Що це |
 * |---|---|---|
 * | `joinedUserId` | бот, при `?start=<код>` | **хто** прийшов — Telegram-id із `ctx.from` |
 * | `joinedBotAt` | бот | коли зайшов **у бота** (часткове приєднання) |
 * | `joinedPlatformAt` | `api-dev` | коли зайшов **на платформу** (повне приєднання) |
 *
 * Власник не вписує id людини навіть коли знає її: вгадане число робило б
 * контакт «приєднаним», а лінк — «використаним», тож обидві дати ставить лише
 * той, хто справді бачив перехід.
 *
 * @module @wwwuabot/shared/contacts
 */

/** Контакт так, як його віддає сервер. */
export interface Contact {
  id: number;
  /** Ім'я, яким власник називає цей контакт. */
  name: string;
  /**
   * `@handle` без `@`; `null` — хендл невідомий. Заповнює **бот**, коли людина
   * приходить за особистим лінком (`COALESCE` — щоб не переписати відоме).
   */
  username: string | null;
  /** Хештеги — ті самі правила, що в нотатках (`@wwwuabot/shared/tags`). */
  tags: string[];
  /** Примітки власника. */
  notes: string;
  /** Код особистого лінка (`inv-8f3k2q`) — поле контакту; `null` — лінка немає. */
  code: string | null;
  /** Готовий діплінк; `null` — лінка немає або імені бота не дізнались. */
  deepLink: string | null;
  /** Telegram-id того, хто прийшов за лінком; `null` — ще ніхто. */
  joinedUserId: number | null;
  /** Коли зайшов **у бота** (часткове приєднання); `null` — ще ні. */
  joinedBotAt: string | null;
  /** Коли зайшов **на платформу** (повне приєднання); `null` — ще ні. */
  joinedPlatformAt: string | null;
  createdAt: string;
  updatedAt: string;
  /**
   * Скільком людям **цей** контакт (як власник) закріпив контакт — другий
   * рівень схеми залучених. Рахує сервер одним запитом на весь список.
   */
  invitedCount: number;
}

/**
 * Те, що власник заповнює в картці: і створення, і правка — **та сама форма**.
 *
 * Одна форма на дві дії навмисно: картка редагує всі поля одразу, і другий
 * опис «що можна створити» проти «що можна змінити» розійшовся б із першим на
 * першій же правці.
 *
 * **Чого тут немає — навмисно.** Немає `owner_id` (його бере сервер із
 * підписаного `initData`), немає `username` (його знає лише бот — людина
 * приходить за лінком), і немає ні `joinedUserId`, ні дат приєднання: їх
 * ставить той, хто бачив перехід, а не той, хто заводить запис.
 *
 * `username` у формі не просто «схований»: сервер його з тіла запиту
 * **не читає**, тож надісланий клієнтом хендл нічого не змінює ні при
 * створенні, ні при правці.
 */
export interface ContactInput {
  name: string;
  tags: string[];
  notes: string;
}

/** Відповідь списку: контакти власника, найсвіжіші згори. */
export interface ContactListResponse {
  ok?: boolean;
  contacts?: Contact[];
  error?: string;
}

/** Відповідь створення, правки й лінка: той рядок, який справді ліг у базу. */
export interface ContactSaveResponse {
  ok?: boolean;
  contact?: Contact;
  error?: string;
}

/** Відповідь видалення — щоб клієнт не вважав зникнення контакту випадковим. */
export interface ContactDeleteResponse {
  ok?: boolean;
  error?: string;
}
