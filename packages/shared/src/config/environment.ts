/**
 * Середовища, у яких працює код.
 *
 * Одне слово — один стан. Це не формальність: розбіжність між тим, як
 * середовище назване в конфізі воркера (`wrangler.toml`) і як його перевіряє
 * код, **не ловить ні typecheck, ні око** — вона проявляється лише як дивна
 * поведінка в деві чи, гірше, як неправильні фільтри в Sentry.
 *
 * Тому значення живуть в одному місці, а не рядками по файлах.
 *
 * **На 12.09.2026 задеплоєні лише дев-воркери** (`bot-dev`, `api-dev`,
 * `web-platform-dev`, `web-admin-dev`, БД `wwwuabot-db-dev`). Прода немає;
 * код писався так, щоб прод вмикався **конфігом**, а не правками в логіці.
 *
 * @module packages/shared/src/config/environment
 */

/** Дев: усі чотири задеплоєні воркери. */
export const ENV_DEV = "dev";

/** Прод: майбутній деплой (окремі воркери + окрема БД). */
export const ENV_PRODUCTION = "production";

/**
 * Чи це прод?
 *
 * Єдине місце, де приймається це рішення. **Прод — тільки явне
 * `"production"`**: усе інше (порожнє значення, одруківка, старий `"prod"`)
 * трактується як дев. Це навмисний перекіс у безпечний бік — ціна помилки
 * «показали підказку для розробника в деві» нульова, а ціна протилежної
 * помилки в проді — витік діагностики користувачам.
 */
export function isProduction(environment?: string): boolean {
  return environment === ENV_PRODUCTION;
}
