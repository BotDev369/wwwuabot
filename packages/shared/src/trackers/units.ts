/**
 * Довідник одиниць власних трекерів: типові одиниці, згруповані за
 * спорідненістю — час іде поруч із часом, вага — з вагою. Група це **підпис
 * у виборі, а не нова сутність**: одиниця лишається текстом, тож трекери,
 * створені до довідника, читаються як читалися. Порядок — від великої до
 * дрібної. Правила — в `docs/TRACKERS.md`.
 * @module @wwwuabot/shared/trackers/units
 */

/** Рядок довідника: одна споріднена група одиниць. */
export interface TrackerUnitGroup {
  /** Ключ групи — стабільний підпис (React-key, тести), а не текст у базі. */
  key: string;
  /** Підпис групи у виборі. */
  title: string;
  /** Одиниці групи: саме цей текст людина бачить біля числа. */
  units: readonly string[];
}

/**
 * Типові одиниці. Список закритий для **вибору**, а не для вводу: своя
 * одиниця («балів», «разів» поза довідником) досі можлива — довідник
 * скорочує звичний шлях, а не забороняє рідкісний.
 */
export const TRACKER_UNIT_GROUPS: readonly TrackerUnitGroup[] = [
  {
    key: "time",
    title: "Час",
    units: [
      "рік",
      "півроку",
      "квартал",
      "місяць",
      "півмісяця",
      "декада",
      "тиждень",
      "доба",
      "ніч",
      "день",
      "година",
      "хв",
      "сек",
    ],
  },
  { key: "distance", title: "Відстань", units: ["км", "м", "см", "мм"] },
  { key: "mass", title: "Вага", units: ["т", "кг", "г", "мг"] },
  { key: "volume", title: "Об'єм", units: ["л", "мл", "склянки"] },
  { key: "count", title: "Кількість", units: ["шт", "разів"] },
  { key: "money", title: "Гроші", units: ["грн", "дол", "євро"] },
];

/** Чи є текст одиницею з довідника — вибір відрізняє від своєї одиниці. */
export function isTrackerUnit(value: string): boolean {
  return TRACKER_UNIT_GROUPS.some((group) => group.units.includes(value));
}
