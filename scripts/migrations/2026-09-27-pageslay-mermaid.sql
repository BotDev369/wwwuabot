UPDATE shop_products
   SET title = 'Русалка — підводний світ',
       summary = '11 сторінок · PDF для друку',
       description = 'Розмальовка «Русалка» — 11 сторінок підводного світу для дітей. Русалки, морські черепахи, дельфини, восьминоги й океанські замки — готово до друку й розфарбовування.

Що всередині
- 11 унікальних розмальовок
- Русалка верхи на морській черепасі
- Королева-русалка на троні
- Русалки з дельфинами
- Сцени підводного селища
- Морські замки й коралові світи
- Формати A4 і US Letter 8,5×11 дюймів
- 300 DPI — чіткий і якісний друк
- Друк необмежену кількість разів вдома
- Підходить для кольорових олівців і маркерів

Як отримати
- Після підтвердження замовлення продавець надсилає PDF у розмові',
       attributes = '[{"name":"Формат","value":"PDF · A4 + Letter"},{"name":"Сторінок","value":"11"},{"name":"Роздільність","value":"300 DPI"},{"name":"Файли","value":"2 PDF"}]',
       updated_at = datetime('now')
 WHERE id = 302 AND shop_id = 34;

