-- Прибрати дубль головної сторінки: `slug = 'main'`
--
-- Що відбулося. Головна сторінка має **порожню** адресу — це `HOME_SLUG` у
-- спільному резолвері (`packages/shared/src/content/resolve.ts`), і рядок з
-- нею створює `2026-09-14-scenarios-03-home-page.sql`. Поруч із ним у базі
-- опинився ще один рядок, `slug = 'main'`, — друга адреса для тієї самої
-- сторінки. Через це в базі було два кандидати на головну, а `pickContentPage`
-- міг повернути будь-який: одна й та сама адреса `/` відповідала б на два
-- різні екрани.
--
-- ⛔ Чому `slug = ''` тут НЕ видаляється. Порожня адреса — це не «застаріле»,
-- а робоча адреса головної сторінки: на неї відповідає і `/start` без
-- параметра, і `/` у вебі. Видаливши її, ми забрали б головну сторінку
-- продукту, а не дубль. Тому умова нижче — саме лише `main`.
--
-- -- Чому саме зараз. Бот став закритим за запрошеннями, і людина без
-- `users.inviter_id` бачить відмову замість контенту
-- (`bot-dev/src/modules/access`). Тому рядок, який не відкривається ні з вебу,
-- ні з бота, лише плутає: він претендує на головну й не може її віддати.
--
-- Ідемпотентна: повторний запуск видаляє 0 рядків, а не падає.
--
-- Звіт: файл показує, **що саме** було видалено, — рядки, а не лише їх
-- кількість. Вибір за власником «правильний» рядок — це тихо втратити чужий
-- контент (AGENTS.md §7), тому список «до» лишається в звіті.
--
-- Запуск (з кореня репозиторію, див. `docs/D1_OPS.md`):
--   npx wrangler d1 execute wwwuabot-db-dev --remote \
--     --config api-dev/wrangler.toml \
--     --file scripts/migrations/2026-09-30-drop-legacy-main-scenario.sql
-- ═════════════════════════════════════════════════════════════════════════════

-- Звіт «до»: рядки-кандидати на головну. Порожня адреса тут для порівняння —
-- її не чіпаємо, і у звіті видно, чи вона взагалі є.
SELECT id,
       slug,
       title,
       is_active,
       owner_id
  FROM scenarios
 WHERE slug IN ('', 'main')
 ORDER BY slug, id;

-- Видаляємо лише дубль. Якщо рядка з `slug = 'main'` немає — нічого не станеться.
DELETE FROM scenarios
 WHERE slug = 'main';

-- Звіт «після»: дубль зник, головна (`slug = ''`) лишилася на місці.
SELECT id,
       slug,
       title
  FROM scenarios
 WHERE slug IN ('', 'main')
 ORDER BY slug, id;
