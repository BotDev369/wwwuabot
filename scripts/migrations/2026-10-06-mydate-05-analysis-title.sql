-- Заголовок екрана аналізу: `props.title` → «Аналіз дати».
--
-- «За датою народження» обіцяє більше, ніж екран дає: дату вводять руками, і
-- це не обов'язково день народження. Змінюємо **одне поле в рядку контенту**,
-- а не весь `page_data`: `json_set` лишає решту блоку недоторканою, тож правка
-- не затирає нічого, що з'явилось у сторінці після міграції-творця.
-- Повторний запуск безпечний — значення те саме.

UPDATE scenarios
SET page_data = json_set(page_data, '$.zones.main[0].props.title', 'Аналіз дати')
WHERE slug = 'mydate/analysis';

SELECT changes() AS updated_rows;
