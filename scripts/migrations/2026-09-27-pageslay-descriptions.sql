-- Контент магазину PageSlay — описи всіх товарів (магазин 34, товари 301–306).
--
-- Це **запис контенту, а не міграція схеми**: таблицю `shop_products` створює
-- `ensureTables` у `api-dev/src/services/shop/shops.ts`, а тут лише
-- перезаписуються рядки, які продавець залив із лістингів Etsy.
--
-- **Навіщо.** Магазин зібрано з шести карток Etsy, і кожна принесла свій
-- формат: «Солярпанк» — мова сторінки з розділювачами `━━━` й емодзі,
-- «Сердиті коти» та «Загін дивних створінь» — короткий вступ і один список,
-- «Повсякденні моменти» — суцільний стовпчик рядків, «Neko Girls» — узагалі
-- вискоблений текст сторінки Etsy (меню, «Добавить в корзину», «С учетом НДС»,
-- «Перевод Google») з її ж повідомленням про миттєве завантаження. Читач у
-- картці бачив шість різних продуктів, хоч товар один.
--
-- **Що зроблено:** той самий **один формат для всіх шести** — короткий вступ
-- абзацами, далі розділи з однаковими назвами в однаковому порядку:
-- «Що всередині» → «Що ви отримаєте» → «Для кого» → «Як отримати» →
-- «Маленький шрифт». Розділ стає заголовком лише тоді, коли за ним ідуть
-- пункти (`detailSections`, `store-view.ts`), тож розмітка тут — не
-- прикраса, а контракт із поверхнею: назва розділу, під нею самі `-` пункти.
-- Емодзі прибрано (тоді як `check:quality` рахує емодзі в UI помилкою,
-- `AGENTS.md` §4), розділювачі `━━━` більше не потрібні — їх малює розділ.
--
-- **Другий прохід — після того, як характеристики переїхали під ціну.**
-- Поверхня товару тепер показує формат, кількість сторінок і роздільність
-- плитками під ціною, тож розділ «Що ви отримаєте» більше не переказує їх
-- словами (це те саме питання, тільки на п'ять екранів нижче). У ньому
-- лишилось те, чого в характеристиках немає: що файл готовий до друку вдома,
-- чим його розфарбовувати й що друкувати можна без обмежень.
--
-- **Чого не робили:** нічого не скорочували. Усе, що було в лістингах —
-- сюжети, кількість сторінок, формати, товщина контурів, жарти («ваші коти
-- все одно зіштовхнуть їх зі столу», «ей, ми вас не засуджуємо»), бонусний
-- довідник кольорів і правила використання, — лишилось; додано лише те, що
-- дописується з самих же карток: сюжети «Для кого», спільний «Як отримати»
-- і «Маленький шрифт». Текст сторінки Etsy, який описом не був (меню,
-- кнопки, «С учетом НДС», «Перевод Google»), не переносився.
--
-- **«Як отримати» — наше, а не з Etsy.** Там файл віддає сама платформа
-- одразу після оплати, у нас PDF надсилає продавець у розмові
-- (`docs/SHOPS.md` §9) — обіцяти покупцеві миттєве завантаження означало б
-- написати в картці те, чого продукт не робить.
--
-- **`attributes` доповнено, а не перебрано:** `Роздільність` (`300 DPI`)
-- додано тим чотирьом товарам, у чиїх лістингах вона названа, а `Neko Girls`
-- дістала `Файли` (`4 PDF`) — саме стільки файлів описує його ж лістинг.
-- Нічого вигаданого: де джерело мовчить, там поле й лишається неповним.
--
-- Повторний запуск ідемпотентний: `WHERE id = … AND shop_id = 34` перезаписує
-- ті самі поля.
--
-- Запуск (з кореня репозиторію, див. `docs/DATA_MODEL.md`):
--   npx wrangler d1 execute wwwuabot-db-dev --remote \
--     --config api-dev/wrangler.toml \
--     --file scripts/migrations/2026-09-27-pageslay-descriptions.sql
