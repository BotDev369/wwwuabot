-- Ремонт page_data, яку в базу записали з екранованими лапками.
--
-- Було: `{\"version\":1,…}` — зворотні скоси перед лапками лишились у тексті,
-- бо лапки зайве екранували під час ручного запису. Це не JSON, тож
-- `parsePageConfig` повертав null і сторінка показувала «Сторінка тимчасово
-- недоступна».
-- Стало: справжній JSON. Умова — рівно те, що зламалось: текст починається з
-- `{\"`. Легітимний JSON так не починається, тому `replace` не зачепить
-- звичайні сторінки з екранованими лапками всередині рядків.
--
-- Ідемпотентно: після заміни умова вже хибна.

UPDATE scenarios
   SET page_data = replace(page_data, '\"', '"'),
       updated_at = datetime('now')
 WHERE substr(page_data, 1, 3) = '{\"'
   AND instr(page_data, '\"') > 0;
