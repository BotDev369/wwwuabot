-- Контакти: два входи замість одного «приєднався» (18.09.2026)
--
-- Було: `telegram_user_id` (хто прийшов) і `joined_at` — одна дата на все, а
-- сама колонка id правила за два різні факти: власник міг вписати туди число
-- руками, і контакт ставав «приєднаним», а лінк — «використаним» без жодного
-- переходу (і навпаки: стерте поле знімало заборону й відкривало лінк знову).
--
-- Стало: id того, хто прийшов, пише лише бот, і входів два — у бота й на
-- платформу. Людина може зайти в бота й не відкрити платформу: це **часткове**
-- приєднання, і без другої дати його не було б видно.
--
-- Порядок виконання: спершу ця міграція, потім деплой api-dev і bot-dev —
-- старий код читає старі імена колонок, новий код нові, і проміжок між ними
-- показує порожні дати замість помилки лише тому, що `ensureTables` додає
-- відсутні колонки сам.
--
-- `joined_platform_at` наявним рядкам **не виставляємо**: ми не знаємо, чи
-- та людина колись відкривала платформу (бот бачив лише вхід у бота), і
-- вигадана дата тут гірша за порожню клітинку. Дату виставить api-dev сам,
-- коли ця людина наступного разу зайде на платформу.

ALTER TABLE contacts RENAME COLUMN telegram_user_id TO joined_user_id;
ALTER TABLE contacts RENAME COLUMN joined_at TO joined_bot_at;
ALTER TABLE contacts ADD COLUMN joined_platform_at TEXT;
