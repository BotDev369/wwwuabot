/**
 * Хто має право бачити бот — одне правило, без бази й Telegram.
 *
 * **Чому це окремим модулем, а не рядком в роутері.** Рішення «показати контент
 * чи відмовити» читається в одному місці (роутер) і пишеться тест без бази,
 * мока й Telegram. Правило, розмазане по конвеєру, рано чи пізно розійшлося б
 * між `/start`, callback'ом і текстом — і відмовити стало б можна тільки на
 * одному шляху.
 *
 * **Допуск — це факт, а не правець.** `users.role` (`admin`) і `users.inviter_id`
 * приходять рядком із бази, тому перевірка мусить бути терпимою до відсутньої
 * колонки: старий `SELECT *` без `withAutoMigrate` дав би `undefined`, і людина,
 * яку щойно запросили, побачила б відмову замість вітання.
 *
 * @module bot-dev/src/modules/access/access
 */

/**
 * Роль, якій допуск не потрібен: власник проєкту йому не запрошували — він сам
 * запрошує.
 */
export const ACCESS_ROLE = "admin";

/**
 * Чи бачить ця людина контент бота.
 *
 * `inviter_id` — головна ознака: його пише той самий перехід, що закріплює
 * контакт, тож «хто запросив» і «за ким прийшли» не розходяться.
 */
export function hasBotAccess(
  user: { role?: unknown; inviter_id?: unknown } | null | undefined,
): boolean {
  if (!user) return false;
  if (user.role === ACCESS_ROLE) return true;

  // Додатне ціле, а не просто ціле: `users.user_id` — це Telegram-id, він не може
  // бути нулем, тож `0` у колонці — це «запрошував невідомий», а не допуск.
  return typeof user.inviter_id === "number" && Number.isInteger(user.inviter_id)
    ? user.inviter_id > 0
    : false;
}
