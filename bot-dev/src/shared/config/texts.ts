/**
 * Тексти повідомлень бота.
 *
 * `ENVIRONMENT` береться з `wrangler.toml` воркера. **На 12.09.2026 бот
 * задеплоєний як `bot-dev` з `ENVIRONMENT = "dev"`** — прода ще немає, тож
 * користувачі бачать підказку для розробника. Це правильно: середовище одне,
 * і воно дев.
 *
 * Раніше тут порівнювалось `"prod"`, а у `wrangler.toml` стояло `"dev"` —
 * два різні слова для одного стану. Саме цю розбіжність і усуває спільний
 * `isProduction()`: вирішує **одна** функція, а не рядок у кожному файлі.
 *
 * Це ж значення їде в Sentry як `environment`, тому розбіжність плутала б ще
 * й фільтри помилок у панелі — дев-події виглядали б як продові.
 *
 * Тут же лежить вітання за запрошенням: це теж текст бота, і тримати речення
 * біля рендера означало б шукати його в коді екрана.
 *
 * @module bot-dev/src/shared/config/texts
 */

import { isProduction } from "@wwwuabot/shared/config/environment";

export const TEXTS = {
  error: (env: string) =>
    isProduction(env)
      ? "Вибачте, сталася технічна помилка. Ми вже працюємо над її вирішенням. 🛠"
      : "⚠️ Сталася помилка (Dev mode). Деталі в логах Cloudflare.",
};

/**
 * Вітання тому, хто прийшов за особистим лінком контакту.
 *
 * Його бачать **лише з першого переходу** (див. `applyContactPayload`): це
 * відповідь на дію «мене запросили», а не екран входу в бота, тому вдруге воно
 * було б брехнею про те, що сталося щойно.
 *
 * Ім'я приходить із ланцюга підписів продукту (ім'я на платформі → Telegram):
 * так та сама людина зветься однаково й тут, і в розмові на платформі.
 *
 * `null` — людини немає в нашій базі (вона завела контакт, але в бота не
 * заходила). Тоді вітальне речення обходиться без імені: вставити туди щось
 * замість нього означало б назвати людину вигадкою.
 */
export const INVITE_GREETING = (name: string | null): string =>
  `${name ? `<b>${name}</b> запрошує вас` : "Вас запрошують"} до конфіденційної бесіди.\n\n` +
  "Відкрийте чат — і зможете написати одне одному. Усе листування бачите тільки ви двоє.";

/**
 * Кнопка, що веде в розмову з тим, хто запросив.
 *
 * Саме `web_app`, а не посилання: людина вже в Telegram, і розмова — це екран
 * платформи, а не зовнішня сторінка. Куди саме веде адреса — знає спільний
 * `@wwwuabot/shared/messages` (`messagesPeerPath`), бо ту саму адресу читає
 * платформа.
 */
export const INVITE_BUTTON = "Відкрити чат";
