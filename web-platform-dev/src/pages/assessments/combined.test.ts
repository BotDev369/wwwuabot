/**
 * Сторож спільного висновку: **кожна комбінація має текст, і блок пояснює себе.**
 *
 * Шість комбінацій §7.5 — це шість різних відповідей людині. Якщо для
 * комбінації немає тексту, вона мовчить найважливіше: «обидва разом» або
 * «тривога переважає». Тому прогалина в мапі падає тестом, а не порожнім
 * заголовком на екрані.
 *
 * Друга половина цього файлу — про мову. Власник 29.09.2026 показав скриншот
 * блоку й запитав, що це за нерозбірливий шматок на початку екрана. Причина
 * була не в розмітці, а в словах: «Разом за двома шкалами» не пояснювало
 * нічого, «Переважають симптоми зниженого настрою» вимагало словника, а
 * числа стояли без знаменників. Тому слова теж під охороною.
 */
import { describe, expect, it } from "vitest";
import { combinedKeyOf, type CombinedKey } from "@wwwuabot/shared/assessments";
import { COMBINED_HEADLINE, COMBINED_TEXTS, SAFETY_POINTER } from "./combined";

const ALL: readonly CombinedKey[] = [
  "comorbid",
  "mood-dominant",
  "anxiety-dominant",
  "mild-both",
  "low-both",
  "border",
];

/** Слова, якими описують **інструмент**, а не людину. */
const JARGON = [
  /\bшкал/i,
  /\bдепрес\w* симптом\w*/i,
  /\bвиражений стрес\b/i,
  /\bклінічн/i,
  /\bпоточні показники\b/i,
  /\bрезультат по шкалі\b/i,
];

describe("покриття комбінацій", () => {
  it("усі шість комбінацій мають заголовок і текст", () => {
    for (const key of ALL) {
      expect(COMBINED_TEXTS[key]?.title, key).toBeTruthy();
      expect(COMBINED_TEXTS[key]?.body, key).toBeTruthy();
    }
  });

  it("кожна комбінація з `combinedKeyOf` має текст — без дірок у покритті", () => {
    // Перебір реальних сум, а не списку ключів: так знайдеться комбінація,
    // яку хтось забув додати у «дані», додавши ключ у типи.
    for (let phq = 0; phq <= 27; phq += 1) {
      for (let gad = 0; gad <= 21; gad += 1) {
        expect(COMBINED_TEXTS[combinedKeyOf(phq, gad)], `${phq}/${gad}`).toBeTruthy();
      }
    }
  });
});

/**
 * Регресія: **людина має зрозуміти блок із першого рядка й без словника.**
 *
 * Блок стоїть над картками тестів, тож це перше, що вона читає, — і раніше за
 * власні числа. «Разом за двома шкалами» не пояснювало, що це за блок і
 * навіщо він; «Переважають симптоми…» вимагало знати, що таке «переважати».
 */
describe("мова блоку", () => {
  it("перший рядок каже, що це за блок", () => {
    expect(COMBINED_HEADLINE).toContain("Два тести");
    expect(COMBINED_HEADLINE).toContain("висновок");
  });

  it("жоден заголовок не описує інструмент замість людини", () => {
    for (const key of ALL) {
      for (const pattern of JARGON) {
        expect(COMBINED_TEXTS[key].title, `${key} / ${pattern}`).not.toMatch(pattern);
      }
    }
  });

  it("кожен заголовок називає стан звичайними словами", () => {
    // Заголовок — це те, що читають першим, тож він мусить бути про стан, а не
    // про комбінацію ключів: «переважає», «співіснують», «супроводжує» — це
    // слова аналітика, а не людини, яка щойно пройшла тест.
    for (const key of ALL) {
      expect(COMBINED_TEXTS[key].title, key).toMatch(/настрій|тривог|стан|дистрес|меж/i);
    }
  });

  it("посилання на безпеку каже, про що питання, і куди йти", () => {
    // Раніше тут було «відповідь на питання безпеки» — внутрішня назва без
    // змісту, яка відправляла людину в нікуди.
    expect(SAFETY_POINTER).toContain("Настрій і депресія");
    expect(SAFETY_POINTER).not.toMatch(/питання безпеки/i);
  });

  it("текст не обіцяє там, де не знає — і каже, що робити далі", () => {
    // Кожен випадок має або пораду, або застереження. Порожній «висновок» без
    // наступного кроку — це те, за що блок існує.
    for (const key of ALL) {
      const body = COMBINED_TEXTS[key].body;
      expect(body, key).toMatch(/порадь|зверніт|пройдіть|повторіть|допомага|не варто/i);
    }
  });
});
