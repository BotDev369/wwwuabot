/**
 * Хабу `/profile` — те, що лишається в нього після «Створити».
 *
 * **Профіль — це про людину, а не про її інструменти.** Доти тут лежали Дати,
 * Контакти, Локації, Нотатки, Сторінки — і хаб був списком робочих місць,
 * серед яких загубився сам акаунт. Тепер усе, що людина **робить**, живе в
 * хабі «Створити» (`/create`, слот «+» у футері), де в кожного пункту два
 * входи — подивитись і створити. А тут лишається те, що про саму людину:
 * рядок акаунта (`UserAccountRow`) і вигляд продукту.
 *
 * **«Тема» веде на свою сторінку** (`/profile/theme`), а не відкриває панель:
 * у теми є розділи — стиль, готові теми (платформа, свої, з простору) і
 * налаштування, — і кожен зі своєю адресою. Модалка не мала ні адреси, ні
 * «назад», тож до збереженої теми не було як повернутись. Обробник
 * (`onOpenTheme`) лишається: хаб не знає про роутер.
 *
 * **Підписів «Мій / Мої» немає** — ні тут, ні в футері, ні на екранах: хаб
 * відкривають зі свого профілю, тож приналежність очевидна, а префікс лише
 * відсуває те слово, за яким пункт упізнають.
 *
 * @module web-platform-dev/src/pages/profile-sections
 */

import type { ShellMenuItem } from "@wwwuabot/ui/menu";

export interface BuildProfileSectionsOptions {
  /** Перейти в розділ теми (`/profile/theme`). Шлях знає той, хто кличе. */
  onOpenTheme: () => void;
}

export function buildProfileSections({
  onOpenTheme,
}: BuildProfileSectionsOptions): ShellMenuItem[] {
  return [{ key: "theme", label: "Тема", icon: "palette", onSelect: onOpenTheme }];
}
