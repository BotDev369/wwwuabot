/**
 * Розділи теми — склад, порядок і адреси.
 *
 * **Три пункти, і це межа.** Стиль (характер продукту), готові теми
 * (бібліотека) і налаштування (створити свою). Свої й чужі теми — не окремі
 * екрани, а три вкладки готових: людина шукає **тему**, а не «мою» чи
 * «публічну» — склад вкладок дає `presets-tabs.ts`.
 *
 * **Дані, а не розмітка.** Одним списком користуються двоє: хаб
 * (`/profile/theme`, рядки) і друга смуга футера (швидкий перехід між
 * сторінками). Дві копії розійшлися б на першій же правці — і кнопка вела б у
 * розділ, якого немає.
 *
 * **Пояснень у пункті немає.** Другий рядок показує **поточний стан** (що
 * вибрано зараз) — його рахує `useThemeLook`; пояснення розділу було текстом,
 * який читають один раз, а стан потрібен щоразу.
 *
 * **Підпис короткий, бо пункт стоїть у смузі.** Три рівні слоти на телефоні — це
 * близько сотні пікселів на пункт: «Налаштувати тему» в них не вміщається й
 * ріжеться трикрапкою. Повну назву носить **заголовок сторінки** («Налаштувати
 * тему»), а пункт навігації — дієслово, за яким його впізнають.
 *
 * @module web-platform-dev/src/pages/themes/theme-sections
 */

import type { IconName } from "@wwwuabot/shared";
// Відносний імпорт, а не аліас `@/`: цей модуль читає тест, а тести ганяються
// з кореневого конфіга без аліасів (`vitest.config.ts`).
import { THEME_PATH } from "../../app/routes";

export type ThemeSection = "style" | "presets" | "customize";

export interface ThemeSectionOption {
  key: ThemeSection;
  label: string;
  icon: IconName;
}

export const THEME_SECTIONS: readonly ThemeSectionOption[] = [
  { key: "style", label: "Стиль", icon: "sliders" },
  { key: "presets", label: "Готові теми", icon: "palette" },
  { key: "customize", label: "Налаштувати", icon: "edit" },
];

/** Адреса розділу — одна на маршрут, пункт смуги й рядок хабу. */
export function themeSectionPath(key: ThemeSection): string {
  return `${THEME_PATH}/${key}`;
}
