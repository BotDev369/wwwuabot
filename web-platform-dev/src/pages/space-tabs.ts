/**
 * Розділи Простору — склад і порядок.
 *
 * **Дані, а не розмітка.** Смугу рендерить спільний `Tabs` (`@wwwuabot/ui/tabs`),
 * той самий, що розділи акаунта: склад живе тут, вигляд — у кирпичику.
 *
 * **Типовий розділ — «Користувачі».** Простір починається з людей: вони
 * з'являються там самі, щойно людина відкриє свій профіль, тоді як оголошення
 * треба ще написати. Порожня перша вкладка читалась би як поламаний екран.
 *
 * **Розділ може бути оголошений, але ще не зроблений** (`soon`). Так чесніше,
 * ніж ховати його: людина бачить, що буде далі, а `SpacePage` каже, що саме
 * там з'явиться, замість порожнечі.
 *
 * @module web-platform-dev/src/pages/space-tabs
 */

export interface SpaceTabOption {
  key: SpaceTab;
  label: string;
  /** Екран ще в розробці: вкладка є, вмісту немає — і це сказано словами. */
  soon?: boolean;
  /** Що саме тут буде — показується замість порожнечі. */
  hint?: string;
}

export const SPACE_TABS: readonly SpaceTabOption[] = [
  {
    key: "users",
    label: "Користувачі",
  },
  {
    key: "ads",
    label: "Оголошення",
    soon: true,
    hint: "Куплю, продам, здам чи зніму, шукаю, обміняю, подарую, надам послуги — усе, що людина хоче сказати іншим.",
  },
  {
    key: "pages",
    label: "Сторінки",
    soon: true,
    hint: "Опубліковані сторінки платформи й користувачів.",
  },
];

export type SpaceTab = "users" | "ads" | "pages";

export const DEFAULT_SPACE_TAB: SpaceTab = "users";

/** Розділ за його ключем — щоб сторінка не тримала другої копії списку. */
export function spaceTab(key: SpaceTab): SpaceTabOption {
  return SPACE_TABS.find((tab) => tab.key === key) ?? SPACE_TABS[0];
}
