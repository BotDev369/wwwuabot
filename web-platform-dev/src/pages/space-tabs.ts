/**
 * Розділи Простору — склад, порядок і вигляд пункту.
 *
 * **Дані, а не розмітка.** Панель рендерить `SpaceNav`, а склад живе тут: пункт
 * несе рівно те, що з нього читає панель, — ключ, підпис і **знак**. Знак
 * обов'язковий, бо згорнута панель лишає саме його: пункт без знака згортався б
 * у порожню клітинку (тип `IconName` цього не дасть зробити мовчки).
 *
 * **Порядок — від того, що наповнюють люди, до власних екранів платформи.**
 * Першими стоять оголошення: дошку читають і пишуть щодня, тож Простір мусить
 * відкриватися нею; «Користувачі» — останні, бо профіль з'являється тут лише
 * після того, як людина сама його відкриє, і порожній перший екран читався б як
 * поламаний Простір. Теми стоять другими (теж наповнюють люди), далі — ігри
 * (єдиний розділ, який не наповнюють: власні екрани платформи) і сторінки.
 *
 * **Розділ може бути оголошений, але ще не зроблений** (`soon`). Так чесніше,
 * ніж ховати його: людина бачить, що буде далі, а `SpacePage` каже, що саме
 * там з'явиться, замість порожнечі.
 *
 * **Розділ є в адресі** (`/space?tab=ads`): у хаб створення «Оголошення» веде
 * саме в цю вкладку, а не в Простір взагалі — інакше замість дошки
 * відкривалася б стрічка людей, і людині довелося б шукати вкладку самій.
 *
 * @module web-platform-dev/src/pages/space-tabs
 */

import type { IconName } from "@wwwuabot/shared";
import { SPACE_PATH } from "../app/routes";

export interface SpaceTabOption {
  key: SpaceTab;
  label: string;
  /** Знак пункту: у згорнутій панелі він лишається сам. */
  icon: IconName;
  /** Екран ще в розробці: вкладка є, вмісту немає — і це сказано словами. */
  soon?: boolean;
  /** Що саме тут буде — показується замість порожнечі. */
  hint?: string;
}

export const SPACE_TABS: readonly SpaceTabOption[] = [
  {
    // Дошка стоїть першою: її наповнюють люди, і вона єдина має що показати
    // відразу — і чужі оголошення, і свої чернетки.
    key: "ads",
    label: "Оголошення",
    icon: "shop",
  },
  {
    // Теми — теж ``контент`` платформи: тему, яку людина відкрила, видно тут
    // поряд з оголошеннями, і взяти її собі можна одним дотиком.
    key: "themes",
    label: "Теми",
    icon: "sparkles",
  },
  {
    // Ігри — єдиний розділ, який **не наповнюють**: він не з даних, а з
    // власних екранів. Тому його вміст ніколи не порожній — і саме тому він
    // стоїть після тих, які залежать від людей.
    key: "games",
    label: "Ігри",
    icon: "play",
  },
  // Сторінки — сторінки, які люди створили з шаблону й відкрили для всіх
  // (перемикач «Публічна сторінка»). Мішанини з контентом платформи тут немає
  // навмисно: у стрічку Простору потрапляє те, що **створили люди**, а
  // сторінки платформи знаходять за їхніми адресами.
  {
    key: "pages",
    label: "Сторінки",
    icon: "layout",
  },
  {
    // Люди — останні: профіль з'являється в Просторі сам, але лише після того,
    // як людина відкриє його в себе, тож цей розділ найчастіше найпорожніший.
    key: "users",
    label: "Користувачі",
    icon: "users",
  },
];

export type SpaceTab = "ads" | "themes" | "games" | "pages" | "users";

export const DEFAULT_SPACE_TAB: SpaceTab = "ads";

/** Розділ за його ключем — щоб сторінка не тримала другої копії списку. */
export function spaceTab(key: SpaceTab): SpaceTabOption {
  return SPACE_TABS.find((tab) => tab.key === key) ?? SPACE_TABS[0];
}

/* ── Розділ в адресі ──────────────────────────────────────────────────────
   Адреса — це **вхід**, а не стан: вона каже, який розділ відкрити, і
   читається один раз, при появі екрана. Далі розділом керує стан, тож
   закриття вкладки не повертає її назад з того самого посилання. */

/** Параметр адреси: `/space?tab=ads` — який розділ показати. */
export const SPACE_TAB_PARAM = "tab";

/**
 * Розділ з адреси. Невідомий ключ (і `null`) дає типовий: у Просторі немає
 * порожнього стану — адреса лише каже, з якої вкладки почати.
 */
export function readSpaceTab(value: string | null): SpaceTab {
  return SPACE_TABS.some((tab) => tab.key === value) ? (value as SpaceTab) : DEFAULT_SPACE_TAB;
}

/**
 * Чи відкрита панель розділів — і це **те саме, що «розділ не названо»**.
 *
 * Розділ в адресі означає, що людина вже обрала: вона прийшла по нього (з хабу
 * «Створити», з посилання), тож панель їй показувати нема чого — вона згорнута
 * до іконок. Типове ж відкриття (`/space`, слот футера) завжди відкриває панель:
 * перш ніж щось показати, треба дати обрати — підписом і знаком, а не самим
 * знаком, який ще нічого не означає.
 */
export function readSpaceNavExpanded(tabParam: string | null): boolean {
  return tabParam === null;
}

/**
 * Адреса розділу — **завжди з параметром**, навіть для типового.
 *
 * Параметр тепер означає не лише «який розділ», а й **«розділ уже обрано»**
 * (`readSpaceNavExpanded`): `/space` відкриває панель, щоб дати обрати, а
 * `/space?tab=ads` приходить по готовий розділ і панель лишається згорнутою.
 * Тому хаб «Створити» і гра вертають людину в **названий** розділ: інакше
 * «подивитись оголошення» відкривало б Простір знову як уперше.
 */
export function spaceTabPath(tab: SpaceTab): string {
  return `${SPACE_PATH}?${SPACE_TAB_PARAM}=${tab}`;
}
