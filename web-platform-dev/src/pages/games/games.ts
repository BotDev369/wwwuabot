/**
 * Ігри Простору — склад, підписи й адреси.
 *
 * **Дані, а не розмітка.** Тим самим списком користуються двоє: вкладка
 * «Ігри» (що показати) і `GameView` (що запустити за ключем). Дві копії
 * розійшлися б на першій же грі — і пункт вів би в гру, якої немає.
 *
 * **Кожна гра має власну адресу** (`/space/g/tictactoe`): за партією стоїть
 * екран, на який «назад» вертає у Простір, а посиланням його можна надіслати.
 * Ключі короткі й латиницею навмисно — це сегмент адреси, а не підпис.
 *
 * **Гра — окремий екран, а не вміст вкладки.** Вкладка відповідає на питання
 * «у що тут можна пограти», партія — на «як воно йде»; змішати їх означало б
 * тримати дошку всередині списку, з якого ще вибирають.
 *
 * @module web-platform-dev/src/pages/games/games
 */

import type { IconName } from "@wwwuabot/shared";
// Відносний імпорт, а не аліас `@/`: цей модуль читає тест, а тести ганяються
// з кореневого конфіга без аліасів (`vitest.config.ts`).
import { SPACE_GAME_PATH } from "../../app/routes";

/**
 * Ключі ігор — вони ж сегменти адреси.
 *
 * Ключ може містити цифри: у «2048» ключ — саме `2048`, бо інша назва тієї
 * самої гри тільки заплутала б адресу (`/space/g/2048`).
 */
export type GameKey = "tictactoe" | "rps" | "guess" | "2048" | "memory" | "nupogodi";

/**
 * Пункт списку ігор — підпис і знак.
 *
 * Пояснень у пункті немає навмисно: рядок під назвою — це висота й шум, а
 * кожна гра каже, що в ній діється, на **своєму** екрані (і каже словами:
 * «курки несуться — підставляйте кошик»). Підпис має лише назвати гру, щоб її
 * впізнали в списку.
 */
export interface GameOption {
  key: GameKey;
  label: string;
  icon: IconName;
}

export const GAMES: readonly GameOption[] = [
  { key: "tictactoe", label: "Хрестики-нулики", icon: "grid" },
  { key: "rps", label: "Камінь, ножиці, папір", icon: "refresh" },
  { key: "guess", label: "Вгадай число", icon: "hash" },
  { key: "2048", label: "2048", icon: "blocks" },
  { key: "memory", label: "Знайди пару", icon: "card" },
  { key: "nupogodi", label: "Ну, погоди!", icon: "egg" },
];

/** Гра за ключем з адреси. `null` — такої гри немає, і це видно екранові. */
export function gameOption(key: string | null | undefined): GameOption | null {
  if (!key) return null;
  return GAMES.find((game) => game.key === key) ?? null;
}

/** Адреса партії — одна на пункт вкладки, маршрут і посилання. */
export function gamePath(key: GameKey): string {
  return `${SPACE_GAME_PATH}/${key}`;
}
