/**
 * Ігри — склад, підписи й адреси.
 *
 * **Дані, а не розмітка.** Тим самим списком користуються двоє: список «Ігри»
 * (що показати) і `GameView` (що запустити за ключем). Дві копії розійшлися б
 * на першій же грі — і пункт вів би в гру, якої немає.
 *
 * **Кожна гра має власну адресу** (`/games/tictactoe`): за партією стоїть
 * екран, на який «назад» вертає до списку, а посиланням його можна надіслати.
 * Ключі короткі й латиницею навмисно — це сегмент адреси, а не підпис.
 *
 * **Гра — окремий екран, а не вміст списку.** Список відповідає на питання
 * «у що тут можна пограти», партія — на «як воно йде»; змішати їх означало б
 * тримати дошку всередині списку, з якого ще вибирають.
 *
 * @module web-platform-dev/src/pages/games/games
 */

// Відносний імпорт, а не аліас `@/`: цей модуль читає тест, а тести ганяються
// з кореневого конфіга без аліасів (`vitest.config.ts`).
import { GAMES_PATH } from "../../app/routes";
// Тип, а не значення: у рантаймі цього імпорту немає, тож він не тягне JSX
// у збірку воркерів (та сама причина, що в `icon-names.ts`).
import type { IconName } from "@wwwuabot/shared";

/**
 * Ключі ігор — вони ж сегменти адреси.
 *
 * Ключ може містити цифри: у «2048» ключ — саме `2048`, бо інша назва тієї
 * самої гри тільки заплутала б адресу (`/games/2048`).
 */
export type GameKey = "tictactoe" | "rps" | "guess" | "2048" | "memory";

/**
 * Пункт списку ігор — підпис і **власний глиф**.
 *
 * Глиф — це **тотожність гри**, а не прикраса рядка (правило 23): «2048»,
 * «Камінь, ножиці, папір» і «Знайди пару» впізнають з першого погляду саме за
 * знаком, і п'ять пунктів перестають бути однаковими смугами тексту. Гра має
 * гліф, якого не має жодна інша — інакше знак нічого не розрізняє.
 *
 * Пояснень у пункті немає: рядок під назвою — це висота й шум, а кожна гра
 * каже, що в ній діється, на **своєму** екрані.
 */
export interface GameOption {
  key: GameKey;
  label: string;
  icon: IconName;
}

export const GAMES: readonly GameOption[] = [
  // Гліфи — рівно ті, що вже є в наборі й кажуть суть гри; вигаданих імен
  // не буває (їх валить компілятор, див. `icon-names.ts`).
  { key: "tictactoe", label: "Хрестики-нулики", icon: "mark-x" },
  { key: "rps", label: "Камінь, ножиці, папір", icon: "rock" },
  { key: "guess", label: "Вгадай число", icon: "question" },
  { key: "2048", label: "2048", icon: "blocks" },
  { key: "memory", label: "Знайди пару", icon: "layers" },
];

/** Гра за ключем з адреси. `null` — такої гри немає, і це видно екранові. */
export function gameOption(key: string | null | undefined): GameOption | null {
  if (!key) return null;
  return GAMES.find((game) => game.key === key) ?? null;
}

/** Адреса партії — одна на пункт списку, маршрут і посилання. */
export function gamePath(key: GameKey): string {
  return `${GAMES_PATH}/${key}`;
}
