/**
 * Українські форми множини — в одному місці.
 *
 * «1 спроба», «2 спроби», «5 спроб»: три форми, і без них екран пише
 * «1 спроб» або «5 спроба». Це дрібниця — але саме з дрібниць складається те,
 * чи читається продукт як зроблений.
 *
 * **Форм дві, і це не надмірність.** «Вгадано за 1 спробу» і «1 спроба» —
 * різні відмінки того самого слова, і одна функція не може дати обидва.
 * Тому тут селектор, а конкретні форми — готові набори при ньому.
 *
 * Живе тут, а не в грі, бо потрібне **кільком** іграм одразу («вгадай число»,
 * «знайди пару», «весела рибалка»), а друга копія цієї логіки завжди
 * розходиться з першою.
 *
 * @module web-platform-dev/src/pages/games/plural
 */

/** Три форми українського іменника: для 1, для 2–4 і для решти. */
export type PluralForms = readonly [one: string, few: string, many: string];

/**
 * Форма для числа.
 *
 * Числа 11–14 — окрема гілка: вони беруть форму множини, хоч і закінчуються на
 * 1–4 («11 спроб», а не «11 спроба»).
 */
export function plural(count: number, forms: PluralForms): string {
  const hundred = count % 100;
  if (hundred >= 11 && hundred <= 14) return forms[2];
  const tail = count % 10;
  if (tail === 1) return forms[0];
  if (tail >= 2 && tail <= 4) return forms[1];
  return forms[2];
}

/** «1 спроба», «2 спроби», «5 спроб» — називний відмінок. */
export const ATTEMPTS: PluralForms = ["спроба", "спроби", "спроб"];

/** «за 1 спробу», «за 2 спроби», «за 5 спроб» — знахідний. */
export const ATTEMPTS_ACCUSATIVE: PluralForms = ["спробу", "спроби", "спроб"];

/** «1 риба», «2 риби», «5 риб» — про спіймане в рибалці. */
export const FISH: PluralForms = ["риба", "риби", "риб"];
