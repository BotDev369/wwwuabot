/**
 * Ополонка — те, що гра **дає**: смуги, політ і жереб.
 *
 * **Окремо від партії, і це не поділ заради рядків.** Вовк, ведро, життя й
 * рівень — те, чим керує гравець і що вирішує вода (`fishing.ts`); смуги, дуга
 * польоту й те, який предмет вистрибне наступним, — те, що **дано**: жодне з
 * цих рішень не залежить від ходу людини. Тримаючи їх в одному модулі,
 * довелось би в одному місці шукати і «як ходить вовк», і «як летить рибина».
 *
 * @module web-platform-dev/src/pages/games/fishing-pond
 */

/** Смуг чотири: на телефоні ведро не встигає за більшою кількістю. */
export const LANES = 4;

/** Кожен четвертий стрибок — чобіт: те саме, що витягли разом із рибою. */
export const BOOT_CHANCE = 0.25;

/** Пауза перед першим стрибком — побачити ополонку, а не почати з удару. */
export const FIRST_GAP_MS = 900;

/** Пауза між стрибками (мс). Рівень її скорочує — цим гра й стає важчою. */
export function gapMs(level: number): number {
  return 1100 - (level - 1) * 120;
}

/** Що вистрибує з ополонки. */
export type ItemKind = "fish" | "boot";

/** Предмет у польоті. */
export interface Leap {
  /** Номер у партії — він же ключ розмітки: без нього рибина «переїжджала» б у сусідню. */
  id: number;
  lane: number;
  kind: ItemKind;
  /** Частка польоту: 0 — вистрибнула з води, 1 — вертається у воду (або в ведро). */
  air: number;
}

/** Смуга, у якій зараз ведро, — найближча до вовка. */
export function laneOf(wolf: number): number {
  return Math.min(LANES - 1, Math.max(0, Math.round(wolf)));
}

/** Де на екрані стоїть смуга — у відсотках ширини, разом із дробовою позицією вовка. */
export function lanePercent(at: number): number {
  return ((at + 0.5) / LANES) * 100;
}

/**
 * Висота польоту: `0` — вода, `1` — вершина дуги.
 *
 * Дуга, а не рівна лінія: у риби тому **дві** фази — угору (легко
 * підготуватись) і вниз (ловити вже пізно), і саме з цього видно, коли ведро
 * мусить бути на місці.
 */
export function arcOf(air: number): number {
  const t = Math.min(1, Math.max(0, air));
  return 4 * t * (1 - t);
}

/** Що вода випустила цього разу — і коли випустить наступне. */
export interface Cast {
  leap: Leap;
  /** Пауза до наступного стрибка, мс. */
  nextIn: number;
}

/**
 * Жереб: у яку смугу, що саме й коли.
 *
 * Випадковість приходить **аргументом** — партія лишається відтворюваною в
 * тесті, а не «приблизно такою ж». Питають її тричі: смуга, вид предмета,
 * пауза. Пауза хитається навколо рівня, бо рівний ритм вивчається напам'ять і
 * партія перестає бути партією вже на третьому рівні.
 */
export function cast(level: number, nextId: number, random: () => number): Cast {
  const lane = Math.min(LANES - 1, Math.floor(random() * LANES));
  const kind: ItemKind = random() < BOOT_CHANCE ? "boot" : "fish";
  return {
    leap: { id: nextId, lane, kind, air: 0 },
    nextIn: gapMs(level) * (0.75 + random() * 0.5),
  };
}
