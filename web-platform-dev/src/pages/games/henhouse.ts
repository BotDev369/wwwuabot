/**
 * Курник — те, що «Ну, погоди!» **дає**: сідала, доріжки й жереб.
 *
 * **Окремо від партії, і це не поділ заради рядків.** Вовк, кошик, життя й
 * рівень — те, чим керує гравець і що вирішує підлога (`nupogodi.ts`); скільки
 * доріжок, як довго яйце котиться до кошика й яка курка знесеться наступною —
 * те, що **дано**: жодне з цих рішень не залежить від ходу людини. В одному
 * модулі довелося б в одному місці шукати і «як ходить вовк», і «як котиться
 * яйце».
 *
 * @module web-platform-dev/src/pages/games/henhouse
 */

/** Доріжок чотири: на телефоні кошик не встигає за більшою кількістю. */
export const LANES = 4;

/** Пауза перед першим яйцем — побачити курник, а не почати з удару. */
export const FIRST_GAP_MS = 900;

/** Пауза між яйцями (мс). Рівень її скорочує — цим гра й стає важчою. */
export function gapMs(level: number): number {
  return 1150 - (level - 1) * 130;
}

/**
 * Скільки яйце котиться доріжкою (мс).
 *
 * Довший шлях — довший час на хід, і саме це є складність: перше яйце котиться
 * 1.6 с, а на пʼятому рівні — рівно секунду. Числа узгоджені з `walkMs` у
 * `nupogodi.ts` так, щоб на останньому рівні вовк усе ще встигав перейти три
 * доріжки (3 × `walkMs` < `fallMs`): інакше партія ставала б неважкою, а
 * неможливою.
 */
export function fallMs(level: number): number {
  return 1600 - (level - 1) * 150;
}

/** Яйце на доріжці. */
export interface Egg {
  /** Номер у партії — він же ключ розмітки: без нього яйце «переїжджало» б у сусідню. */
  id: number;
  lane: number;
  /** Частка шляху: 0 — щойно з-під курки, 1 — докотилось до кошика. */
  drop: number;
}

/** Доріжка, у якій зараз кошик, — найближча до вовка. */
export function laneOf(wolf: number): number {
  return Math.min(LANES - 1, Math.max(0, Math.round(wolf)));
}

/** Де на екрані стоїть доріжка — у відсотках ширини, разом із дробовою позицією вовка. */
export function lanePercent(at: number): number {
  return ((at + 0.5) / LANES) * 100;
}

/**
 * Висота яйця на доріжці у відсотках: 0 — під куркою, 100 — у кошику.
 *
 * Яйце котиться **вниз**, а не летить дугою: у курнику воно падає з сідала
 * просто в кошик, і саме тому в нього одна фаза, а не дві. Хід у гравця
 * лишається: побачити яйце треба **до** того, як воно долетить.
 */
export function dropPercent(drop: number): number {
  return Math.min(1, Math.max(0, drop)) * 100;
}

/** Що курник дав цього разу — і коли дасть наступне. */
export interface Lay {
  egg: Egg;
  /** Пауза до наступного яйця, мс. */
  nextIn: number;
}

/**
 * Жереб: яка курка знесеться і коли.
 *
 * Випадковість приходить **аргументом** — партія лишається відтворюваною в
 * тесті, а не «приблизно такою ж». Питають її двічі: доріжка й пауза. Пауза
 * хитається навколо рівня, бо рівний ритм вивчається напамʼять і партія
 * перестає бути партією вже на третьому рівні.
 */
export function lay(level: number, nextId: number, random: () => number): Lay {
  const lane = Math.min(LANES - 1, Math.floor(random() * LANES));
  return {
    egg: { id: nextId, lane, drop: 0 },
    nextIn: gapMs(level) * (0.75 + random() * 0.5),
  };
}
