/**
 * Спільний вигляд списку Простору — пошук, **один на всі розділи**.
 *
 * **Смуга керування обов'язкова в кожному розділі** — і стоїть вона другим
 * рядком екрана: перший — знак панели й назва розділу, другий — те, чим список
 * керують, далі — список. Розділ без смуги ламав би цей лад: на одних екранах
 * другий рядок є, на інших немає, і око щоразу шукає список в іншому місці.
 *
 * **Що саме звужує список — знає екран.** Тут лишається те, що є в кожного
 * розділу: запит. Поля, за якими шукати, передає розділ — вони в нього різні
 * (ім'я гри, назва теми, автор сторінки), і спільне правило не мусить знати
 * жодного з них.
 *
 * **Порядок і розкладку списку не чіпаємо.** Даних у цих розділів мало, порядок
 * дає база (свіжіші першими), а вибір вигляду є лише там, де вигляд справді
 * різний — у дошки оголошень (`ads-view.ts`): рядок шикує ціну з містом в один
 * рядок, плитка ставить стовпчиком. У решти розділів вигляду один, тож і
 * клітинки вигляду немає — вона обіцяла б дію, якої немає (§7).
 *
 * @module web-platform-dev/src/pages/space-list-view
 */

import { queryWords } from "@wwwuabot/ui/collection";

/**
 * Стан смуги розділу: те, що людина в ній набрала.
 *
 * Один тип на всі розділи навмисно: смуга мусить поводитись однаково, а
 * розширювати його — це міняти **всі** екрани разом, а не по одному.
 */
export interface SpaceListView {
  query: string;
}

/** Типове — порожній запит: список читають повним. */
export const DEFAULT_SPACE_LIST_VIEW: SpaceListView = { query: "" };

/**
 * Клас списку розділу — кирпичик `.wb-collection*` у вигляді рядків.
 *
 * Константа, а не літерал у розмітці: той самий клас мусить стояти в усіх
 * чотирьох списках Простору, інакше проміжки між рядками в них розійдуться
 * (див. `space.css`).
 */
export const SPACE_LIST_CLASS = "wb-collection wb-collection--rows";

/**
 * Чи проходить рядок пошук.
 *
 * Слова запиту з'єднуються через «і» — так само, як у дошки оголошень: «вася
 * khmen» мусить знайти рядок, де є обидва, а не все, де є хоч одне. Поля бере
 * розділ: шукають за тим, що **видно в рядку**, — інакше знайдене неможливо
 * впізнати на екрані.
 */
export function filterByQuery<T>(
  items: readonly T[],
  query: string,
  fields: (item: T) => readonly (string | null | undefined)[],
): T[] {
  const words = queryWords(query);
  if (words.length === 0) return [...items];

  return items.filter((item) => {
    const haystack = fields(item)
      .filter((part): part is string => typeof part === "string" && part !== "")
      .join(" ")
      .toLocaleLowerCase("uk-UA");
    return words.every((word) => haystack.includes(word));
  });
}

/** Чип вибраного: те, що змінила смуга, і дотик, який повертає це назад. */
export interface SpaceListChip {
  key: string;
  label: string;
  action: string;
  /** Що станеться, коли чип прибирають (єдиний вибір у смузі — запит). */
  reset: SpaceListView;
}

/**
 * Чипи смуги — те, що вона звужує.
 *
 * Порожній запит чипа не має: постійний «усе» займав би місце й говорив би про
 * те, що й так видно зі списку.
 */
export function listChips(view: SpaceListView): SpaceListChip[] {
  const query = view.query.trim();
  if (!query) return [];

  return [
    {
      key: "query",
      label: `«${query}»`,
      action: `Прибрати пошук «${query}»`,
      reset: { query: "" },
    },
  ];
}
