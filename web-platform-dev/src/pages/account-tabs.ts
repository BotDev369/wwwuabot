/**
 * Розділи сторінки акаунта — **дані**, а не розмітка.
 *
 * Розділів рівно два, і вони не «сторінки» й не вкладки футера: це два різні
 * акаунти однієї людини — **платформа** (ім'я, яке вона обрала тут, і фото, яке
 * вона поставить) та **Telegram** (усе, що віддав Telegram, як є). Тримати їх
 * окремо велить не оформлення: ім'я на платформі можна змінити, Telegram-юзернейм
 * — ні, і злите в один список воно читалось би як одне поле, яке десь
 * редагується, а десь ні.
 *
 * Тут лише ключ і підпис: розмітку дає сторінка, а вигляд розділу — свої
 * компоненти. Порядок — не абетковий (AGENTS.md §7): першим стоїть розділ,
 * з якого починають, і це `DEFAULT_ACCOUNT_TAB`, а не випадковий порядок
 * масиву.
 *
 * @module web-platform-dev/src/pages/account-tabs
 */

export const ACCOUNT_TABS = [
  { key: "platform", label: "Платформа" },
  { key: "telegram", label: "Телеграм" },
] as const;

export type AccountTab = (typeof ACCOUNT_TABS)[number]["key"];

/**
 * Розділ, який відкривається першим — **Telegram**.
 *
 * На акаунт приходять із футера («Я»), а не за правкою імені: спершу людина
 * бачить те, що в неї вже є (дані Telegram), і вже потім — те, що обирає сама.
 */
export const DEFAULT_ACCOUNT_TAB: AccountTab = "telegram";
