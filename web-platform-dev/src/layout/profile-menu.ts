/**
 * Склад меню профілю — того, що відкривається дотиком до «Профіль» у футері.
 *
 * Тут лише **склад**: пункти, їхні адреси й те, що кожен із них обіцяє. Саму
 * поверхню, правило дотику й вигляд заглушки дає спільний `MenuModal`
 * (`@wwwuabot/ui/menu`) — та сама пара «склад ↔ розмітка», що у футера
 * (`platform-tabs.ts` + `@wwwuabot/ui/nav`).
 *
 * **Порядок — за абеткою (А→Я).** «Головного» пункту тут немає: людина
 * приходить за конкретним розділом, і сталий порядок дозволяє запам'ятати його
 * місце. Абетка не залежить від того, хто додав пункт останнім, тож список не
 * переставляється сам собою з кожною правкою.
 *
 * **Підписів «Мій / Мої» немає** — ні тут, ні на екранах, ні в футері. Меню
 * відкривають зі свого профілю, тож приналежність і так очевидна, а префікс
 * лише відсував те слово, за яким пункт упізнають («Контакти», а не
 * «МоїКонтакти»).
 *
 * Поверхня показує ці пункти **плитками по дві в ряду** (`MenuModal` →
 * `layout="blocks"`), а не смугами на всю ширину: сюди тицяють, а смугу на всю
 * ширину читають — вона потрібна там, де несуть пояснення.
 *
 * Пункт без `href` і без дії — заглушка, і це чесно видно ще до дотику: у
 * рядка є пояснення, що там буде (`status: "soon"`). Так само поводиться
 * пункт футера без адреси — краще сказати, ніж мовчки нічого не робити (§7).
 *
 * @module web-platform-dev/src/layout/profile-menu
 */

import { toWebPath } from "@wwwuabot/shared/content";
import type { ShellMenuItem } from "@wwwuabot/ui/menu";

/**
 * Екран «Нотатки» — власний маршрут, а не рядок контенту.
 *
 * Окремий шлях, а не `slug`, з тієї самої причини, що й у профілю: список
 * нотаток збирається з даних людини (`notes`), а не з `page_data` рядка
 * `scenarios` (AGENTS.md §7).
 */
/** Сегмент маршруту (без слеша — так його чекає роутер; `app/router.tsx`). */
export const NOTES_ROUTE = "notes";

/** Адреса того ж екрана — те, на що веде пункт меню. */
export const NOTES_PATH = `/${NOTES_ROUTE}`;

/**
 * Екран «Контакти» — теж власний маршрут.
 *
 * Контакти живуть у своїй таблиці (`contacts`), а не в `page_data`, тож і
 * адреса в них своя — та сама причина, що в нотаток і профілю (§7).
 */
export const CONTACTS_ROUTE = "contacts";

/** Адреса того ж екрана — те, на що веде пункт меню. */
export const CONTACTS_PATH = `/${CONTACTS_ROUTE}`;

/** Вид усередині меню: список розділів або панель теми. */
export type ProfileMenuView = "list" | "theme";

export interface BuildProfileItemsOptions {
  /** Відкрити панель теми: вона живе в тій самій поверхні, окремим видом. */
  onOpenTheme: () => void;
}

export function buildProfileItems({ onOpenTheme }: BuildProfileItemsOptions): ShellMenuItem[] {
  // Абетка, а не «важливість»: Дати → Контакти → Локації → Нотатки → Сторінки →
  // Тема. Порядок перевіряє `profile-menu.test.ts` — переставити розділи
  // випадково дуже легко, бо в коді вони лежать у порядку, а не за абеткою.
  return [
    { key: "mydate", label: "Дати", icon: "my-dates", href: toWebPath("mydate") },
    { key: "contacts", label: "Контакти", icon: "mail", href: CONTACTS_PATH },
    {
      key: "locations",
      label: "Локації",
      icon: "globe",
      status: "soon",
      hint: "Адреси й координати місць, які згадуються у сценаріях.",
    },
    { key: "notes", label: "Нотатки", icon: "text", href: NOTES_PATH },
    {
      key: "pages",
      label: "Сторінки",
      icon: "layout",
      status: "soon",
      hint: "Створені сторінки: адреса, зони й що з них уже опубліковано.",
    },
    { key: "theme", label: "Тема", icon: "sliders", onSelect: onOpenTheme },
  ];
}

/**
 * Панель теми в цьому меню більше не список.
 *
 * Світла й темна зникли зовсім: світлоту виводить сам продукт із **фону**, який
 * задала людина, а кольорів тепер три й усі обов'язкові. Це не пункти списку, а
 * панель (`ThemeColorPanel` з `@wwwuabot/shared`), і поверхня показує її замість
 * списку (`MenuModal` → `content`) — тобто тема лишається однією поверхнею й не
 * стає модалкою над модалкою.
 *
 * Тому тут лишається тільки склад пунктів списку: усе, що стосується вибору
 * кольору, живе в одному спільному місці — і адмінка показує те саме.
 */
